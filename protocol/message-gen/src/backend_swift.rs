//! Swift backend: consumes a SchemaSet (same source as the JSON IR) and emits `Schema.swift`.
//!
//! Everything is generated with literal offsets on top of the small `MessageRuntime` module: per
//! message a plain `struct` (Equatable) with `decode / fromBytes / validate / encode()`, a
//! zero-copy `Reader` with lazy views, a base writer used whenever the struct is inlined, and
//! validators per version block.

use message_core::{element_size, EnumDescriptor, FieldDescriptor, MessageDescriptor, SchemaSet, SimpleType, Type};
use std::fmt::Write as _;

pub fn generate_swift(set: &SchemaSet) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "// Generated by message-rs codegen; do not edit. Source of truth: the Rust #[derive(Message)] definitions.\n// Two-layer API: XxxReader = zero-copy view over RawMessage; Xxx = plain Swift struct (decode /\n// fromBytes / validate / encode() live on it). Map keys are `[K: V]`; Vec<u8> is Data.\n\nimport Foundation\n#if canImport(MessageRuntime)\nimport MessageRuntime\n#endif\n"
    );
    for e in &set.enums {
        write_enum(&mut out, e);
    }
    for m in &set.messages {
        write_message(&mut out, m, set);
    }
    out
}

// ---------- Identifiers and types ----------

fn line(out: &mut String, level: usize, s: &str) {
    let _ = writeln!(out, "{}{s}", "  ".repeat(level));
}

/// Whether struct `name` has extension blocks: containers of it are then written in instance
/// mode (per-element / per-value slots, shape bit set).
fn has_ext(set: &SchemaSet, name: &str) -> bool {
    set.message(name).is_some_and(|m| !m.layout.ext_blocks.is_empty())
}

fn fixed_len_of(set: &SchemaSet, name: &str) -> usize {
    set.message(name).map(|m| m.layout.fixed_len).expect("planned struct")
}

fn camel(s: &str) -> String {
    let mut out = String::new();
    let mut upper = false;
    for c in s.chars() {
        if c == '_' {
            upper = true;
        } else if upper {
            out.extend(c.to_uppercase());
            upper = false;
        } else {
            out.push(c);
        }
    }
    out
}

fn swift_ident(s: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "associatedtype", "class", "deinit", "enum", "extension", "fileprivate", "func", "import", "init",
        "inout", "internal", "let", "open", "operator", "private", "protocol", "public", "static", "struct",
        "subscript", "typealias", "var", "break", "case", "catch", "continue", "default", "defer", "do",
        "else", "fallthrough", "for", "guard", "if", "in", "repeat", "return", "throw", "throws", "rethrows",
        "try", "where", "while", "as", "false", "is", "nil", "self", "Self", "super", "true", "Type",
        "Protocol", "await", "async", "some", "any",
    ];
    if KEYWORDS.contains(&s) {
        format!("`{s}`")
    } else {
        s.to_string()
    }
}

/// Field name: Rust snake_case -> Swift lowerCamelCase (keywords escaped).
fn swift_field(name: &str) -> String {
    swift_ident(&camel(name))
}

/// Enum variant: Rust PascalCase -> Swift lowerCamelCase, keeping acronyms readable
/// (`Red` -> `red`, `URL` -> `url`, `HTTPServer` -> `httpServer`).
fn swift_variant(name: &str) -> String {
    let chars: Vec<char> = name.chars().collect();
    let mut out = String::new();
    let mut i = 0;
    // leading acronym run: every uppercase letter that is not followed by a lowercase one
    while i < chars.len() && chars[i].is_uppercase() && !(i + 1 < chars.len() && chars[i + 1].is_lowercase()) {
        out.extend(chars[i].to_lowercase());
        i += 1;
    }
    if i == 0 {
        // plain word: only the first letter is lowercased
        out.extend(chars[0].to_lowercase());
        i = 1;
    }
    out.extend(chars[i..].iter());
    swift_ident(&out)
}

fn swift_scalar(s: SimpleType) -> &'static str {
    match s {
        SimpleType::Bool => "Bool",
        SimpleType::U8 => "UInt8",
        SimpleType::I8 => "Int8",
        SimpleType::U16 => "UInt16",
        SimpleType::I16 => "Int16",
        SimpleType::U32 => "UInt32",
        SimpleType::I32 => "Int32",
        SimpleType::U64 => "UInt64",
        SimpleType::I64 => "Int64",
        SimpleType::F32 => "Float",
        SimpleType::F64 => "Double",
        SimpleType::String | SimpleType::Bytes => unreachable!("slot-shaped types are not scalars"),
    }
}

fn swift_read_fn(s: SimpleType) -> &'static str {
    match s {
        SimpleType::Bool => "Bool",
        SimpleType::U8 => "U8",
        SimpleType::I8 => "I8",
        SimpleType::U16 => "U16",
        SimpleType::I16 => "I16",
        SimpleType::U32 => "U32",
        SimpleType::I32 => "I32",
        SimpleType::U64 => "U64",
        SimpleType::I64 => "I64",
        SimpleType::F32 => "F32",
        SimpleType::F64 => "F64",
        SimpleType::String | SimpleType::Bytes => unreachable!(),
    }
}

/// `Writer` call for a scalar (signed 8/16-bit values go through the unsigned writers).
fn write_call(s: SimpleType, pos: &str, val: &str) -> String {
    match s {
        SimpleType::Bool => format!("w.writeBool({pos}, {val})"),
        SimpleType::U8 => format!("w.writeU8({pos}, {val})"),
        SimpleType::I8 => format!("w.writeU8({pos}, UInt8(bitPattern: {val}))"),
        SimpleType::U16 => format!("w.writeU16({pos}, {val})"),
        SimpleType::I16 => format!("w.writeU16({pos}, UInt16(bitPattern: {val}))"),
        SimpleType::U32 => format!("w.writeU32({pos}, {val})"),
        SimpleType::I32 => format!("w.writeI32({pos}, {val})"),
        SimpleType::U64 => format!("w.writeU64({pos}, {val})"),
        SimpleType::I64 => format!("w.writeI64({pos}, {val})"),
        SimpleType::F32 => format!("w.writeF32({pos}, {val})"),
        SimpleType::F64 => format!("w.writeF64({pos}, {val})"),
        SimpleType::String | SimpleType::Bytes => unreachable!("slot-shaped types are not scalars"),
    }
}

/// Owned (plain struct) type.
fn swift_owned_ty(ty: &Type) -> String {
    match ty {
        Type::Simple(SimpleType::String) => "String".into(),
        Type::Simple(SimpleType::Bytes) => "Data".into(),
        Type::Simple(s) => swift_scalar(*s).into(),
        Type::Enum { name } => name.clone(),
        Type::Struct { name } => name.clone(),
        Type::Array { body } => format!("[{}]", swift_owned_ty(&body.elem)),
        Type::Map { body } => format!("[{}: {}]", swift_owned_ty(&body.key), swift_owned_ty(&body.value)),
    }
}

/// Reader-side type of a field value.
fn swift_reader_ty(ty: &Type) -> String {
    match ty {
        Type::Simple(SimpleType::String) => "String".into(),
        Type::Simple(SimpleType::Bytes) => "Data".into(),
        Type::Simple(s) => swift_scalar(*s).into(),
        Type::Enum { name } => name.clone(),
        Type::Struct { name } => format!("{name}Reader"),
        Type::Array { body } => view_ty(&body.elem),
        Type::Map { .. } => unreachable!("maps are handled at the field level"),
    }
}

/// View type for array elements.
fn view_ty(elem: &Type) -> String {
    match elem {
        Type::Simple(SimpleType::String) => "StringListView".into(),
        Type::Simple(SimpleType::Bytes) => "BytesListView".into(),
        Type::Simple(s) => format!("ScalarListView<{}>", swift_scalar(*s)),
        Type::Enum { name } => format!("ScalarListView<{name}>"),
        Type::Struct { name } => format!("StructEvoListView<{name}Reader>"),
        Type::Array { .. } => "SlotListView".into(),
        Type::Map { .. } => unreachable!("maps cannot be array elements"),
    }
}

fn is_scalar(t: &Type) -> bool {
    matches!(t, Type::Simple(s) if s.is_scalar())
}

// ---------- Enums ----------

fn write_enum(out: &mut String, e: &EnumDescriptor) {
    let _ = writeln!(out, "public enum {}: Int32, MessageEnum, CaseIterable {{", e.name);
    for v in &e.variants {
        let _ = writeln!(out, "  case {} = {}", swift_variant(&v.name), v.value);
    }
    let _ = writeln!(out, "}}");
    let _ = writeln!(
        out,
        "extension {}: MessageScalar {{\n  public static var width: Int {{ 4 }}\n  public static func read(_ m: RawMessage, _ off: Int) -> {} {{\n    {}(rawValue: m.readI32(off))!\n  }}\n}}\n",
        e.name, e.name, e.name
    );
}

// ---------- Reader ----------

/// View construction over elements of `elem` at `start` with `count` elements.
fn view_ctor(elem: &Type, start: &str, count: &str, _set: &SchemaSet) -> String {
    match elem {
        Type::Simple(SimpleType::String) => format!("StringListView(msg: msg, start: {start}, count: {count})"),
        Type::Simple(SimpleType::Bytes) => format!("BytesListView(msg: msg, start: {start}, count: {count})"),
        Type::Simple(s) => format!(
            "ScalarListView<{}>(msg: msg, start: {start}, count: {count}, stride: {})",
            swift_scalar(*s),
            s.fixed_size()
        ),
        Type::Enum { name } => format!("ScalarListView<{name}>(msg: msg, start: {start}, count: {count}, stride: 4)"),
        // `count` is the raw slot length here: the shape bit selects open vs instance elements
        Type::Struct { name } => format!("StructEvoListView<{name}Reader>(msg: msg, start: {start}, rawLen: UInt32({count}))"),
        Type::Array { .. } => format!("SlotListView(msg: msg, start: {start}, count: {count})"),
        Type::Map { .. } => unreachable!("maps cannot be array elements"),
    }
}

/// Expression reading a value of `ty` at absolute payload position `pos`.
fn read_expr(ty: &Type, pos: &str, set: &SchemaSet) -> String {
    read_expr_hv(ty, pos, "hv", set)
}

/// Same, with the header version passed to nested struct readers (elements and map values get 0).
fn read_expr_hv(ty: &Type, pos: &str, hv: &str, set: &SchemaSet) -> String {
    match ty {
        Type::Simple(SimpleType::String) => format!("msg.readString({pos})"),
        Type::Simple(SimpleType::Bytes) => format!("msg.readBytes({pos})"),
        Type::Simple(s) => format!("msg.read{}({pos})", swift_read_fn(*s)),
        Type::Enum { name } => format!("{name}(rawValue: msg.readI32({pos}))!"),
        Type::Struct { name } => {
            let _ = hv;
            format!("{{ let (o, l) = msg.readSlot({pos}); return {name}Reader(msg: msg, origin: Int(o), end: Int(o) + Int(l), hv: INSTANCE_HV) }}()")
        }
        Type::Array { body } => {
            if body.fixed.is_some() && !body.elem.is_slot_shaped() {
                view_ctor(&body.elem, pos, &body.fixed.unwrap().to_string(), set)
            } else {
                format!(
                    "{{ let (o, l) = msg.readSlot({pos}); return {} }}()",
                    view_ctor(&body.elem, "Int(o)", "Int(l)", set)
                )
            }
        }
        Type::Map { .. } => unreachable!("maps are handled at the field level"),
    }
}

/// Reader-side type of a field (maps get their generated view type).
fn reader_ret_ty(f: &FieldDescriptor) -> String {
    match &f.ty {
        Type::Map { .. } => format!("{}MapView", pascal(&f.name)),
        ty => swift_reader_ty(ty),
    }
}

/// Expression reading field `f` at absolute payload position `pos`.
fn read_field_expr(f: &FieldDescriptor, pos: &str, set: &SchemaSet) -> String {
    match &f.ty {
        Type::Map { .. } => format!(
            "{{ let (o, l) = msg.readSlot({pos}); return {}MapView(msg: msg, start: Int(o), rawLen: l) }}()",
            pascal(&f.name)
        ),
        ty => read_expr(ty, pos, set),
    }
}

/// Value returned for a required extension-block field when the writer's schema predates it.
fn default_expr(ty: &Type, field: &str, set: &SchemaSet) -> String {
    match ty {
        Type::Simple(SimpleType::Bool) => "false".into(),
        Type::Simple(SimpleType::String) => "\"\"".into(),
        Type::Simple(SimpleType::Bytes) => "Data()".into(),
        Type::Simple(_) => "0".into(),
        Type::Enum { .. } | Type::Struct { .. } => {
            format!("fatalError(\"field `{field}` missing: data written by an older schema version\")")
        }
        Type::Array { body } => view_ctor(&body.elem, "0", "0", set),
        Type::Map { .. } => format!("{}MapView(msg: msg, start: 0, rawLen: 0)", pascal(field)),
    }
}

fn pascal(s: &str) -> String {
    let c = camel(s);
    let mut out = String::new();
    let mut chars = c.chars();
    if let Some(f) = chars.next() {
        out.extend(f.to_uppercase());
        out.push_str(chars.as_str());
    }
    out
}

/// Expression turning the reader value `expr` of `ty` into its owned form.
fn owned_expr(ty: &Type, expr: &str, set: &SchemaSet) -> String {
    match ty {
        Type::Simple(_) | Type::Enum { .. } => expr.to_string(),
        Type::Struct { .. } => format!("{expr}.toOwned()"),
        Type::Array { body } => owned_list(&body.elem, expr, set, 0),
        Type::Map { .. } => unreachable!("maps are handled at the field level"),
    }
}

/// `expr` is a view over elements of `elem`; nested dynamic arrays (`SlotListView`) yield slots,
/// so each inner view is rebuilt from its slot before recursing.
fn owned_list(elem: &Type, expr: &str, set: &SchemaSet, depth: usize) -> String {
    match elem {
        Type::Simple(_) | Type::Enum { .. } => format!("Array({expr})"),
        Type::Struct { .. } => format!("{expr}.map {{ $0.toOwned() }}"),
        Type::Array { body } => {
            let s = format!("__s{depth}");
            let inner_view = view_ctor(&body.elem, &format!("Int({s}.0)"), &format!("Int({s}.1)"), set);
            let inner = owned_list(&body.elem, &inner_view, set, depth + 1);
            format!("{expr}.map {{ {s} in return {inner} }}")
        }
        Type::Map { .. } => unreachable!(),
    }
}

fn write_reader(out: &mut String, m: &MessageDescriptor, set: &SchemaSet) {
    let name = &m.name;
    let ext_versions = m.layout.ext_blocks.iter().map(|b| b.version.to_string()).collect::<Vec<_>>().join(", ");
    let _ = writeln!(out, "public struct {name}Reader: MessageReader {{");
    let _ = writeln!(out, "  public static let KEY: UInt32 = {}", m.key);
    let _ = writeln!(out, "  public static let fixedLen: Int = {}", m.layout.fixed_len);
    let _ = writeln!(out, "  public static let EXT_VERSIONS: [UInt16] = [{ext_versions}]");
    let _ = writeln!(out, "  /// The underlying buffer (payload-relative offsets); lets callers build views themselves.");
    let _ = writeln!(out, "  public let msg: RawMessage");
    let _ = writeln!(out, "  let origin: Int");
    let _ = writeln!(out, "  /// End of the extent this view may read (payload end, or instance end for nested structs).");
    let _ = writeln!(out, "  let end: Int");
    let _ = writeln!(out, "  /// The writer's highest extension version (INSTANCE_HV inside self-contained instances).");
    let _ = writeln!(out, "  public let hv: UInt8");
    let _ = writeln!(out, "  public init(msg: RawMessage, origin: Int, end: Int, hv: UInt8) {{");
    let _ = writeln!(out, "    self.msg = msg");
    let _ = writeln!(out, "    self.origin = origin");
    let _ = writeln!(out, "    self.end = end");
    let _ = writeln!(out, "    self.hv = hv");
    let _ = writeln!(out, "  }}");
    let _ = writeln!(
        out,
        "  /// Lazy decode: nil only when the buffer is too short or the key does not match. Call\n  /// `{name}.validate` first on untrusted input."
    );
    let _ = writeln!(
        out,
        "  public static func decode(_ data: Data) -> {name}Reader? {{\n    guard let m = RawMessage(decoding: data, key: KEY, fixedLen: fixedLen) else {{ return nil }}\n    return {name}Reader(msg: m, origin: 0, end: m.payloadCount, hv: m.version)\n  }}"
    );

    for f in &m.fields {
        if f.reserved {
            continue;
        }
        let fname = swift_field(&f.name);
        let ret = reader_ret_ty(f);
        if f.since > 1 {
            let since = f.since;
            let min_len = m.layout.ext_blocks.iter().find(|b| b.version == since).map_or(0, |b| b.fixed_len);
            let find = format!("msg.findExtBlock(Self.EXT_VERSIONS, hv, {since}, {min_len}, lo: origin, hi: end)");
            if f.optional {
                let _ = writeln!(
                    out,
                    "  public var {fname}: {ret}? {{\n    guard let bs = {find}, msg.bitmapBit(bs, {}) else {{ return nil }}\n    return {}\n  }}",
                    f.optional_bit.unwrap_or(0),
                    read_field_expr(f, &format!("bs + {}", f.offset), set)
                );
            } else {
                let _ = writeln!(
                    out,
                    "  public var {fname}: {ret} {{\n    guard let bs = {find} else {{ return {} }}\n    return {}\n  }}",
                    default_expr(&f.ty, &fname, set),
                    read_field_expr(f, &format!("bs + {}", f.offset), set)
                );
            }
        } else if f.optional {
            let _ = writeln!(
                out,
                "  public var {fname}: {ret}? {{\n    guard msg.bitmapBit(origin, {}) else {{ return nil }}\n    return {}\n  }}",
                f.optional_bit.unwrap_or(0),
                read_field_expr(f, &format!("origin + {}", f.offset), set)
            );
        } else {
            let _ = writeln!(out, "  public var {fname}: {ret} {{ {} }}", read_field_expr(f, &format!("origin + {}", f.offset), set));
        }
    }

    // toOwned()
    let mut args = String::new();
    for f in &m.fields {
        if f.reserved {
            continue;
        }
        let fname = swift_field(&f.name);
        let expr = if let Type::Map { body } = &f.ty {
            let vt = swift_owned_ty(&body.value);
            format!(
                "{fname}.reduce(into: [{}: {vt}]()) {{ $0[$1.0] = {} }}",
                swift_owned_ty(&body.key),
                owned_expr(&body.value, "$1.1", set)
            )
        } else if f.optional {
            let inner = owned_expr(&f.ty, "$0", set);
            if inner == "$0" { fname.clone() } else { format!("{fname}.map {{ {inner} }}") }
        } else {
            owned_expr(&f.ty, &fname, set)
        };
        let _ = write!(args, "{fname}: {expr}, ");
    }
    let args = args.trim_end_matches(", ").to_string();
    let _ = writeln!(out, "  public func toOwned() -> {name} {{\n    {name}({args})\n  }}");
    let _ = writeln!(out, "}}");
}

fn write_map_views(out: &mut String, m: &MessageDescriptor, set: &SchemaSet) {
    for f in &m.fields {
        if f.reserved {
            continue;
        }
        let Type::Map { body } = &f.ty else { continue };
        let view = format!("{}MapView", pascal(&f.name));
        let l = message_core::map_entry_layouts(&body.key, &body.value, set).expect("planned map");
        let key_ty = swift_reader_ty(&body.key);
        let val_ty = swift_reader_ty(&body.value);
        let key_read = read_expr_hv(&body.key, "start + i * stride", "0", set);
        // Struct values: the writer's shape bit selects open entries (value = fixed region) or
        // instance entries (value = slot to a self-contained instance).
        let (stride, v_off, val_read) = match body.value.as_ref() {
            Type::Struct { name } => (
                format!("inst ? {} : {}", l.inst_stride, l.open_stride),
                format!("inst ? {} : {}", l.inst_value_offset, l.open_value_offset),
                format!(
                    "let p = start + i * stride + vOff\n    if inst {{ let (o, l) = msg.readSlot(p); return {name}Reader(msg: msg, origin: Int(o), end: Int(o) + Int(l), hv: INSTANCE_HV) }}\n    return {name}Reader(msg: msg, origin: p, end: msg.payloadCount, hv: 0)"
                ),
            ),
            _ => (
                l.open_stride.to_string(),
                l.open_value_offset.to_string(),
                format!("return {}", read_expr_hv(&body.value, "start + i * stride + vOff", "0", set)),
            ),
        };
        let _ = writeln!(out, "public struct {view}: Sequence {{");
        let _ = writeln!(out, "  let msg: RawMessage");
        let _ = writeln!(out, "  let start: Int");
        let _ = writeln!(out, "  let rawLen: UInt32");
        let _ = writeln!(out, "  public var count: Int {{ Int(rawLen & LEN_MASK) }}");
        let _ = writeln!(out, "  var inst: Bool {{ rawLen & SHAPE_BIT != 0 }}");
        let _ = writeln!(out, "  var stride: Int {{ {stride} }}");
        let _ = writeln!(out, "  var vOff: Int {{ {v_off} }}");
        let _ = writeln!(out, "  public var isEmpty: Bool {{ count == 0 }}");
        let _ = writeln!(out, "  public func key(at i: Int) -> {key_ty} {{ {key_read} }}");
        let _ = writeln!(out, "  public func value(at i: Int) -> {val_ty} {{\n    {val_read}\n  }}");
        let _ = writeln!(out, "  public func entry(at i: Int) -> ({key_ty}, {val_ty}) {{ (key(at: i), value(at: i)) }}");
        let _ = writeln!(
            out,
            "  public struct Iterator: IteratorProtocol {{\n    let view: {view}\n    var i = 0\n    public mutating func next() -> ({key_ty}, {val_ty})? {{\n      guard i < view.count else {{ return nil }}\n      defer {{ i += 1 }}\n      return view.entry(at: i)\n    }}\n  }}\n  public func makeIterator() -> Iterator {{ Iterator(view: self) }}\n}}\n"
        );
    }
}

// ---------- Owned struct ----------

fn write_owned_struct(out: &mut String, m: &MessageDescriptor) {
    let name = &m.name;
    let _ = writeln!(out, "public struct {name}: Equatable, MessageCodec {{");
    let mut params = String::new();
    let mut inits = String::new();
    for f in &m.fields {
        if f.reserved {
            continue;
        }
        let fname = swift_field(&f.name);
        let ty = swift_owned_ty(&f.ty);
        let ty = if f.optional { format!("{ty}?") } else { ty };
        let _ = writeln!(out, "  public var {fname}: {ty}");
        let _ = write!(params, "{fname}: {ty}, ");
        let _ = writeln!(inits, "    self.{fname} = {fname}");
    }
    let params = params.trim_end_matches(", ").to_string();
    if params.is_empty() {
        let _ = writeln!(out, "  public init() {{}}");
    } else {
        let _ = writeln!(out, "  public init({params}) {{");
        out.push_str(&inits);
        let _ = writeln!(out, "  }}");
    }
    let _ = writeln!(out, "}}");
}

// ---------- Encoder ----------

/// `func __writeXxxBase(_ w: inout Writer, _ base: Int, _ value: Xxx)`: the base fields of a
/// struct at an already reserved position (inline fields, struct elements, map values).
fn write_base_writer(out: &mut String, m: &MessageDescriptor, set: &SchemaSet) {
    let _ = writeln!(out, "func __write{}Base(_ w: inout Writer, _ base: Int, _ value: {}) {{", m.name, m.name);
    for f in m.fields.iter().filter(|f| f.since == 1) {
        write_field(out, 1, f, &format!("value.{}", swift_field(&f.name)), "base", set);
    }
    let _ = writeln!(out, "}}");
    if !m.layout.ext_blocks.is_empty() {
        // the extension chain, appended after the base var data (top-level message or instance)
        let _ = writeln!(out, "func __write{}Ext(_ w: inout Writer, _ value: {}) {{", m.name, m.name);
        for b in &m.layout.ext_blocks {
            line(out, 1, "do {");
            line(out, 2, &format!("let blk = w.reserve({})", b.fixed_len));
            for f in m.fields.iter().filter(|f| f.since == b.version) {
                write_field(out, 2, f, &format!("value.{}", swift_field(&f.name)), "blk", set);
            }
            line(out, 2, &format!("w.writeTrailer(blk, {})", b.version));
            line(out, 1, "}");
        }
        let _ = writeln!(out, "}}");
    }
    // self-contained instance: fixed region, own var data, extension chain; returns its start
    let _ = writeln!(out, "func __write{}Instance(_ w: inout Writer, _ value: {}) -> Int {{", m.name, m.name);
    line(out, 1, &format!("let s = w.reserve({})", m.layout.fixed_len));
    line(out, 1, &format!("__write{}Base(&w, s, value)", m.name));
    if !m.layout.ext_blocks.is_empty() {
        line(out, 1, &format!("__write{}Ext(&w, value)", m.name));
    }
    line(out, 1, "return s");
    let _ = writeln!(out, "}}");
}

/// `public func encode() -> Data`: header + base + extension blocks, all with literal offsets.
fn write_encode(out: &mut String, m: &MessageDescriptor, set: &SchemaSet) {
    let need = 8 + m.layout.fixed_len;
    let max_version = m.layout.ext_blocks.last().map_or(0, |b| b.version);
    line(out, 1, "/// Canonical encoding (byte-identical to Rust and TS): declaration-order var data, sorted map keys.");
    line(out, 1, "public func encode() -> Data {");
    line(out, 2, &format!("var w = Writer(capacity: {need})"));
    line(out, 2, "w.reserve(8)");
    line(out, 2, &format!("let base = w.reserve({})", m.layout.fixed_len));
    line(out, 2, &format!("__write{}Base(&w, base, self)", m.name));
    if !m.layout.ext_blocks.is_empty() {
        line(out, 2, &format!("__write{}Ext(&w, self)", m.name));
    }
    let _ = set;
    line(out, 2, &format!("w.writeU32(0, {})", m.key));
    line(out, 2, &format!("w.writeU16(4, {})", m.layout.fixed_len));
    line(out, 2, &format!("w.writeU8(6, {max_version})"));
    line(out, 2, "w.writeU8(7, 0)");
    line(out, 2, "return w.finish()");
    line(out, 1, "}");
}

/// Write one field of a block: optional fields set their bitmap bit, reserved fields stay zero.
fn write_field(out: &mut String, level: usize, f: &FieldDescriptor, val: &str, block: &str, set: &SchemaSet) {
    if f.reserved {
        return;
    }
    let pos = format!("{block} + {}", f.offset);
    if f.optional {
        line(out, level, &format!("if let v = {val} {{"));
        line(out, level + 1, &format!("w.setBit({block}, {})", f.optional_bit.unwrap_or(0)));
        write_value_or_map(out, level + 1, f, &f.ty, "v", &pos, set);
        line(out, level, "}");
    } else {
        write_value_or_map(out, level, f, &f.ty, val, &pos, set);
    }
}

fn write_value_or_map(out: &mut String, level: usize, f: &FieldDescriptor, ty: &Type, val: &str, pos: &str, set: &SchemaSet) {
    match ty {
        Type::Map { .. } => write_map_field(out, level, f, val, pos, set),
        _ => write_value(out, level, ty, val, pos, set, 0),
    }
}

fn write_value(out: &mut String, level: usize, ty: &Type, val: &str, pos: &str, set: &SchemaSet, depth: usize) {
    match ty {
        Type::Simple(SimpleType::String) => line(out, level, &format!("w.writeStringSlot({pos}, {val})")),
        Type::Simple(SimpleType::Bytes) => line(out, level, &format!("w.writeDataSlot({pos}, {val})")),
        Type::Simple(s) => line(out, level, &write_call(*s, pos, val)),
        Type::Enum { .. } => line(out, level, &format!("w.writeI32({pos}, {val}.rawValue)")),
        Type::Struct { name } => {
            line(out, level, &format!("do {{ let s = __write{name}Instance(&w, {val}); w.writeSlot({pos}, w.rel(s), w.length - s) }}"));
        }
        Type::Array { body } if matches!(body.elem.as_ref(), Type::Struct { name } if has_ext(set, name)) => {
            // elements with extension fields: per-element instance slots, shape bit set
            let Type::Struct { name } = body.elem.as_ref() else { unreachable!() };
            let (a, i, r) = (format!("a{depth}"), format!("i{depth}"), format!("r{depth}"));
            line(out, level, "do {");
            line(out, level + 1, &format!("let {a} = {val}"));
            line(out, level + 1, &format!("let {r} = w.reserve({a}.count * 8)"));
            line(out, level + 1, &format!("for ({i}, v{depth}) in {a}.enumerated() {{"));
            line(out, level + 2, &format!("let s = __write{name}Instance(&w, v{depth})"));
            line(out, level + 2, &format!("w.writeSlot({r} + {i} * 8, w.rel(s), w.length - s)"));
            line(out, level + 1, "}");
            line(out, level + 1, &format!("w.writeSlot({pos}, w.rel({r}), Int(UInt32({a}.count) | SHAPE_BIT))"));
            line(out, level, "}");
        }
        Type::Array { body } => {
            let (a, i, r) = (format!("a{depth}"), format!("i{depth}"), format!("r{depth}"));
            if body.fixed.is_some() && !body.elem.is_slot_shaped() {
                let w = element_size(&body.elem, set).expect("planned");
                line(out, level, &format!("for ({i}, v{depth}) in {val}.prefix({}).enumerated() {{", body.fixed.unwrap()));
                write_open_elem(out, level + 1, &body.elem, &format!("v{depth}"), &format!("{pos} + {i} * {w}"), set, depth + 1);
                line(out, level, "}");
            } else {
                let w = element_size(&body.elem, set).expect("planned");
                line(out, level, "do {");
                line(out, level + 1, &format!("let {a} = {val}"));
                line(out, level + 1, &format!("let {r} = w.reserve({a}.count * {w})"));
                line(out, level + 1, &format!("for ({i}, v{depth}) in {a}.enumerated() {{"));
                write_open_elem(out, level + 2, &body.elem, &format!("v{depth}"), &format!("{r} + {i} * {w}"), set, depth + 1);
                line(out, level + 1, "}");
                line(out, level + 1, &format!("w.writeSlot({pos}, w.rel({r}), {a}.count)"));
                line(out, level, "}");
            }
        }
        Type::Map { .. } => unreachable!("maps are written by write_map_field"),
    }
}

/// An element of a shape=0 (open) array or an unevolved map value: struct elements are written as
/// their fixed-region footprint at `pos` (their var data appended), everything else as a value.
fn write_open_elem(out: &mut String, level: usize, ty: &Type, val: &str, pos: &str, set: &SchemaSet, depth: usize) {
    match ty {
        Type::Struct { name } => line(out, level, &format!("__write{name}Base(&w, {pos}, {val})")),
        _ => write_value(out, level, ty, val, pos, set, depth),
    }
}

/// A map field: entries sorted by the key's wire value.
fn write_map_field(out: &mut String, level: usize, f: &FieldDescriptor, val: &str, pos: &str, set: &SchemaSet) {
    let Type::Map { body } = &f.ty else { unreachable!("write_map_field on a non-map") };
    let stride = f.element_size.expect("planned stride");
    let v_off = f.map_value_offset.expect("planned value offset");
    let sort = match body.key.as_ref() {
        Type::Simple(SimpleType::String) => "o.keys.sorted { $0.utf8.lexicographicallyPrecedes($1.utf8) }".to_string(),
        Type::Enum { .. } => "o.keys.sorted { $0.rawValue < $1.rawValue }".to_string(),
        _ => "o.keys.sorted()".to_string(),
    };
    let key_write = match body.key.as_ref() {
        Type::Simple(SimpleType::String) => "w.writeStringSlot(e, k)".to_string(),
        Type::Enum { .. } => "w.writeI32(e, k.rawValue)".to_string(),
        Type::Simple(s) => write_call(*s, "e", "k"),
        _ => unreachable!("invalid map key rejected by the planner"),
    };
    line(out, level, "do {");
    line(out, level + 1, &format!("let o = {val}"));
    line(out, level + 1, &format!("let ks = {sort}"));
    line(out, level + 1, &format!("let r = w.reserve(ks.count * {stride})"));
    line(out, level + 1, "for (i, k) in ks.enumerated() {");
    line(out, level + 2, &format!("let e = r + i * {stride}"));
    line(out, level + 2, &key_write);
    match body.value.as_ref() {
        Type::Struct { name } if has_ext(set, name) => {
            write_value(out, level + 2, &body.value, "o[k]!", &format!("e + {v_off}"), set, 0)
        }
        _ => write_open_elem(out, level + 2, &body.value, "o[k]!", &format!("e + {v_off}"), set, 0),
    }
    line(out, level + 1, "}");
    let len = match body.value.as_ref() {
        Type::Struct { name } if has_ext(set, name) => "Int(UInt32(ks.count) | SHAPE_BIT)".to_string(),
        _ => "ks.count".to_string(),
    };
    line(out, level + 1, &format!("w.writeSlot({pos}, w.rel(r), {len})"));
    line(out, level, "}");
}

// ---------- Validator ----------

fn write_validators(out: &mut String, m: &MessageDescriptor, set: &SchemaSet) {
    let _ = writeln!(out, "func __validate{}Base(_ m: RawMessage, _ base: Int, _ hv: UInt8) throws {{", m.name);
    for f in m.fields.iter().filter(|f| f.since == 1) {
        validate_field(out, 1, f, "base", set);
    }
    let _ = writeln!(out, "}}");
    for b in &m.layout.ext_blocks {
        let _ = writeln!(out, "func __validate{}V{}(_ m: RawMessage, _ base: Int, _ hv: UInt8) throws {{", m.name, b.version);
        for f in m.fields.iter().filter(|f| f.since == b.version) {
            validate_field(out, 1, f, "base", set);
        }
        let _ = writeln!(out, "}}");
    }
    // self-contained instance in [lo, hi): base, then every extension block the chain offers
    // (no version is promised inside an instance, so absent blocks are legal)
    let _ = writeln!(out, "func __validate{}Inst(_ m: RawMessage, _ lo: Int, _ hi: Int) throws {{", m.name);
    line(out, 1, &format!("try __validate{}Base(m, lo, INSTANCE_HV)", m.name));
    for b in m.layout.ext_blocks.iter().rev() {
        let v = b.version;
        line(out, 1, &format!(
            "if let bs = m.findExtBlock({name}Reader.EXT_VERSIONS, INSTANCE_HV, {v}, {fixed}, lo: lo, hi: hi) {{ try __validate{name}V{v}(m, bs, INSTANCE_HV) }}",
            name = m.name,
            fixed = b.fixed_len
        ));
    }
    let _ = writeln!(out, "}}");
}

fn write_validate(out: &mut String, m: &MessageDescriptor) {
    let r = format!("{}Reader", m.name);
    line(out, 1, "/// Strictly check an untrusted buffer; after nil no accessor can trap.");
    line(out, 1, "public static func validate(_ data: Data) -> ValidationError? {");
    line(out, 2, "do {");
    line(out, 2, &format!("  let m = try RawMessage(validating: data, key: {r}.KEY, fixedLen: {r}.fixedLen)"));
    line(out, 2, &format!("  try __validate{}Base(m, 0, m.version)", m.name));
    for b in m.layout.ext_blocks.iter().rev() {
        let v = b.version;
        line(out, 2, &format!("  if m.version >= {v} {{"));
        line(out, 2, &format!("    let bs = try checkExtBlock(m, {r}.EXT_VERSIONS, m.version, {v}, {})", b.fixed_len));
        line(out, 2, &format!("    try __validate{}V{v}(m, bs, m.version)", m.name));
        line(out, 2, "  }");
    }
    line(out, 2, "  return nil");
    line(out, 2, "} catch let e as ValidationError {");
    line(out, 2, "  return e");
    line(out, 2, "} catch {");
    line(out, 2, "  preconditionFailure(\"validate can only throw ValidationError\")");
    line(out, 2, "}");
    line(out, 1, "}");
}

fn validate_field(out: &mut String, level: usize, f: &FieldDescriptor, block: &str, set: &SchemaSet) {
    if f.reserved {
        return;
    }
    let pos = format!("{block} + {}", f.offset);
    let field = swift_field(&f.name);
    let open = |out: &mut String, level: usize| {
        if f.optional {
            let _ = writeln!(out, "{}if m.bitmapBit({block}, {}) {{", "  ".repeat(level), f.optional_bit.unwrap_or(0));
        }
    };
    let close = |out: &mut String, level: usize| {
        if f.optional {
            let _ = writeln!(out, "{}}}", "  ".repeat(level));
        }
    };
    match &f.ty {
        // arrays and maps locate their own errors (region + per element)
        Type::Array { .. } | Type::Map { .. } => {
            let body = validate_body(&f.ty, &pos, &field, f, set, 0, None);
            let inner = if f.optional { level + 1 } else { level };
            let pad = "  ".repeat(inner);
            open(out, level);
            let _ = writeln!(out, "{pad}do {{");
            for l in body.lines().filter(|l| !l.trim().is_empty()) {
                let _ = writeln!(out, "{pad}  {l}");
            }
            let _ = writeln!(out, "{pad}}}");
            close(out, level);
        }
        _ => {
            let Some(leaf) = leaf_stmt(&f.ty, &pos) else { return };
            let inner = if f.optional { level + 1 } else { level };
            open(out, level);
            emit_nested(out, inner, &field, None, &leaf);
            close(out, level);
        }
    }
}

/// Bare check statement for a leaf-shaped value (scalars need nothing).
fn leaf_stmt(ty: &Type, pos: &str) -> Option<String> {
    match ty {
        Type::Simple(SimpleType::String) => Some(format!("try checkStrSlot(m, {pos})")),
        Type::Simple(SimpleType::Bytes) => Some(format!("try checkBytesSlot(m, {pos})")),
        Type::Simple(_) => None,
        Type::Enum { name } => Some(format!("try checkEnum({name}.self, m, {pos})")),
        Type::Struct { name } => Some(format!("let (lo, hi) = try checkInstance(m, {pos})\ntry __validate{name}Inst(m, lo, hi)")),
        _ => unreachable!("arrays and maps are handled by validate_body"),
    }
}

/// `try nest(field[, index]) { body }`; `body` lines are re-indented under the block.
fn emit_nested(out: &mut String, level: usize, field: &str, index: Option<&str>, body: &str) {
    let indent = "  ".repeat(level);
    match index {
        Some(i) => { let _ = writeln!(out, "{indent}try nest(\"{field}\", {i}) {{"); }
        None => { let _ = writeln!(out, "{indent}try nest(\"{field}\") {{"); }
    }
    let inner = "  ".repeat(level + 1);
    for l in body.lines().filter(|l| !l.trim().is_empty()) {
        let stripped = l.trim_start();
        let relative = (l.len() - stripped.len()) / 2;
        let _ = writeln!(out, "{}{}{}", inner, "  ".repeat(relative), stripped);
    }
    let _ = writeln!(out, "{indent}}}");
}

/// Self-contained statements checking an array or map at `pos`: region failures are located by
/// the labelled `checkRegion`, element failures by `nest` closures. `idx` is the index of the
/// enclosing element (nested arrays), `depth` keeps loop variables unique.
fn validate_body(ty: &Type, pos: &str, field: &str, f: &FieldDescriptor, set: &SchemaSet, depth: usize, idx: Option<&str>) -> String {
    let mut out = String::new();
    let idx_arg = idx.map(|i| format!(", {i}")).unwrap_or_default();
    let emit = |out: &mut String, body: String| {
        for l in body.lines().filter(|l| !l.trim().is_empty()) {
            let _ = writeln!(out, "  {}", l);
        }
    };
    match ty {
        Type::Array { body } => {
            let w = element_size(&body.elem, set).expect("element size of a planned schema");
            if body.fixed.is_some() && !body.elem.is_slot_shaped() {
                let i = format!("i{depth}");
                if let Some(leaf) = leaf_stmt(&body.elem, &format!("{pos} + {i} * {w}")) {
                    line(&mut out, 0, &format!("for {i} in 0..<{} {{", body.fixed.unwrap()));
                    emit_nested(&mut out, 1, field, Some(&i), &leaf);
                    line(&mut out, 0, "}");
                }
            } else if let Type::Struct { name } = body.elem.as_ref() {
                // the writer's shape bit selects open footprints vs instance slots
                let fixed = fixed_len_of(set, name);
                let (o, n, s, i) = (format!("o{depth}"), format!("n{depth}"), format!("s{depth}"), format!("i{depth}"));
                line(&mut out, 0, &format!("let ({o}, {n}, {s}) = try checkRegionShape(m, {pos}, \"{field}\"{idx_arg})"));
                line(&mut out, 0, &format!("if {s} {{"));
                line(&mut out, 1, &format!("for {i} in 0..<{n} {{"));
                emit_nested(&mut out, 2, field, Some(&i), &format!("let (lo, hi) = try checkInstance(m, {o} + {i} * 8)\ntry __validate{name}Inst(m, lo, hi)"));
                line(&mut out, 1, "}");
                line(&mut out, 0, "} else {");
                line(&mut out, 1, &format!("try checkExtent(m, {o}, {n}, {fixed}, \"{field}\"{idx_arg})"));
                line(&mut out, 1, &format!("for {i} in 0..<{n} {{"));
                emit_nested(&mut out, 2, field, Some(&i), &format!("try __validate{name}Base(m, {o} + {i} * {fixed}, 0)"));
                line(&mut out, 1, "}");
                line(&mut out, 0, "}");
            } else if is_scalar(&body.elem) {
                line(&mut out, 0, &format!("try checkRegion(m, {pos}, {w}, \"{field}\"{idx_arg})"));
            } else {
                let (o, n, i) = (format!("o{depth}"), format!("n{depth}"), format!("i{depth}"));
                line(&mut out, 0, &format!("let ({o}, {n}) = try checkRegion(m, {pos}, {w}, \"{field}\"{idx_arg})"));
                line(&mut out, 0, &format!("for {i} in 0..<{n} {{"));
                let elem_pos = format!("{o} + {i} * {w}");
                if let Type::Array { .. } = body.elem.as_ref() {
                    emit(&mut out, validate_body(&body.elem, &elem_pos, field, f, set, depth + 1, Some(&i)));
                } else if let Some(leaf) = leaf_stmt(&body.elem, &elem_pos) {
                    emit_nested(&mut out, 1, field, Some(&i), &leaf);
                }
                line(&mut out, 0, "}");
            }
        }
        Type::Map { body } => {
            let stride = f.element_size.expect("planned stride");
            let v_off = f.map_value_offset.expect("planned value offset");
            if is_scalar(&body.key) && is_scalar(&body.value) {
                line(&mut out, 0, &format!("try checkRegion(m, {pos}, {stride}, \"{field}\"{idx_arg})"));
                return out;
            }
            let (o, n, i) = (format!("o{depth}"), format!("n{depth}"), format!("i{depth}"));
            if let Type::Struct { name } = body.value.as_ref() {
                // shape bit selects the entry layout: open (value = fixed region) or instance slot
                let l = message_core::map_entry_layouts(&body.key, &body.value, set).expect("planned map");
                let s = format!("s{depth}");
                line(&mut out, 0, &format!("let ({o}, {n}, {s}) = try checkRegionShape(m, {pos}, \"{field}\"{idx_arg})"));
                line(&mut out, 0, &format!("let st = {s} ? {} : {}", l.inst_stride, l.open_stride));
                line(&mut out, 0, &format!("let vo = {s} ? {} : {}", l.inst_value_offset, l.open_value_offset));
                line(&mut out, 0, &format!("try checkExtent(m, {o}, {n}, st, \"{field}\"{idx_arg})"));
                line(&mut out, 0, &format!("for {i} in 0..<{n} {{"));
                line(&mut out, 1, &format!("let e = {o} + {i} * st"));
                if let Some(leaf) = leaf_stmt(&body.key, "e") {
                    emit_nested(&mut out, 1, field, Some(&i), &leaf);
                }
                line(&mut out, 1, &format!("if {s} {{"));
                emit_nested(&mut out, 2, field, Some(&i), &format!("let (lo, hi) = try checkInstance(m, e + vo)\ntry __validate{name}Inst(m, lo, hi)"));
                line(&mut out, 1, "} else {");
                emit_nested(&mut out, 2, field, Some(&i), &format!("try __validate{name}Base(m, e + vo, 0)"));
                line(&mut out, 1, "}");
                line(&mut out, 0, "}");
                return out;
            }
            line(&mut out, 0, &format!("let ({o}, {n}) = try checkRegion(m, {pos}, {stride}, \"{field}\"{idx_arg})"));
            line(&mut out, 0, &format!("for {i} in 0..<{n} {{"));
            line(&mut out, 1, &format!("let e = {o} + {i} * {stride}"));
            if let Some(leaf) = leaf_stmt(&body.key, "e") {
                emit_nested(&mut out, 1, field, Some(&i), &leaf);
            }
            let v_pos = format!("e + {v_off}");
            if let Type::Array { .. } = body.value.as_ref() {
                emit(&mut out, validate_body(&body.value, &v_pos, field, f, set, depth + 1, Some(&i)));
            } else if let Some(leaf) = leaf_stmt(&body.value, &v_pos) {
                emit_nested(&mut out, 1, field, Some(&i), &leaf);
            }
            line(&mut out, 0, "}");
        }
        _ => unreachable!("validate_body handles arrays and maps only"),
    }
    out
}

// ---------- Per message ----------

fn write_message(out: &mut String, m: &MessageDescriptor, set: &SchemaSet) {
    write_reader(out, m, set);
    write_map_views(out, m, set);
    write_owned_struct(out, m);
    write_base_writer(out, m, set);
    write_validators(out, m, set);
    let _ = writeln!(out, "extension {} {{", m.name);
    let _ = writeln!(out, "  public static var messageKey: UInt32 {{ {}Reader.KEY }}", m.name);
    let _ = writeln!(out, "  public static func decode(_ data: Data) -> {}Reader? {{\n    {}Reader.decode(data)\n  }}", m.name, m.name);
    let _ = writeln!(out, "  public static func fromBytes(_ data: Data) -> {name}? {{\n    {}Reader.decode(data)?.toOwned()\n  }}", m.name, name = m.name);
    write_validate(out, m);
    write_encode(out, m, set);
    let _ = writeln!(out, "}}");
}

//! Kotlin backend: consumes a SchemaSet (same source as the JSON IR) and emits `Schema.kt`.
//!
//! Everything is generated with literal offsets on top of the small `message.rs` runtime: per
//! message a `data class` (decode / fromBytes / validate on its companion, `encode()` on the
//! instance), a zero-copy `Reader` with lazy views, a base writer used whenever the struct is
//! inlined, and validators per version block.

use message_core::{element_size, EnumDescriptor, FieldDescriptor, MessageDescriptor, SchemaSet, SimpleType, Type};
use std::fmt::Write as _;

/// Package of the hand-written runtime; the generated code defaults to the same package.
pub const RUNTIME_PACKAGE: &str = "message.rs";

/// Runtime symbols the generated code refers to; imported when the package is not the runtime's.
const RUNTIME_IMPORTS: &[&str] = &[
    "BytesListView", "MapEntry", "MessageEnum", "MessageEnumCompanion", "MessageReader", "MessageScalar", "RawMessage",
    "INSTANCE_HV", "LEN_MASK", "SHAPE_BIT", "ScalarListView", "SlotListView", "StringListView", "StructEvoListView",
    "UTF8_STRING_ORDER", "ValidationError", "Writer", "checkBytesSlot", "checkEnum", "checkExtBlock", "checkExtent",
    "checkIndex", "checkInstance", "checkRegion", "checkRegionShape", "checkStrSlot",
    "contentEquals", "contentHashCode", "nest", "runValidation",
];

pub fn generate_kotlin(set: &SchemaSet, package: &str) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "// Generated by message-rs codegen; do not edit. Source of truth: the Rust #[derive(Message)] definitions.\n\
         // Two-layer API: XxxReader = zero-copy view over RawMessage; Xxx = plain Kotlin data class (decode /\n\
         // fromBytes / validate live on its companion, encode() on the instance). Map keys keep their type;\n\
         // Vec<u8> is ByteArray.\n\npackage {package}"
    );
    if package != RUNTIME_PACKAGE {
        out.push('\n');
        for sym in RUNTIME_IMPORTS {
            let _ = writeln!(out, "import {RUNTIME_PACKAGE}.{sym}");
        }
    }
    out.push('\n');
    for e in &set.enums {
        write_enum(&mut out, e);
    }
    for m in &set.messages {
        write_message(&mut out, m, set);
    }
    out
}

// ---------- Identifiers and types ----------

fn line(out: &mut String, level: usize, s: &str) {
    if s.is_empty() {
        out.push('\n');
    } else {
        let _ = writeln!(out, "{}{s}", "    ".repeat(level));
    }
}

/// Lines of a nested statement block, each with its indentation relative to the block start.
type Lines = Vec<(usize, String)>;

fn emit(out: &mut String, level: usize, lines: &Lines) {
    for (l, s) in lines {
        line(out, level + l, s);
    }
}

fn camel(s: &str) -> String {
    let mut out = String::new();
    let mut upper = false;
    for c in s.chars() {
        if c == '_' {
            upper = true;
        } else if upper {
            out.extend(c.to_uppercase());
            upper = false;
        } else {
            out.push(c);
        }
    }
    out
}

fn pascal(s: &str) -> String {
    let c = camel(s);
    let mut out = String::new();
    let mut chars = c.chars();
    if let Some(f) = chars.next() {
        out.extend(f.to_uppercase());
        out.push_str(chars.as_str());
    }
    out
}

fn kotlin_ident(s: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is", "null",
        "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "typeof", "val", "var",
        "when", "while", "abstract", "actual", "annotation", "by", "catch", "companion", "const", "constructor",
        "crossinline", "delegate", "dynamic", "enum", "expect", "external", "file", "final",
        "finally", "get", "import", "infix", "init", "inline", "inner", "internal", "lateinit", "noinline", "open",
        "operator", "override", "param", "private", "property", "protected", "public", "reified", "receiver",
        "sealed", "set", "setparam", "suspend", "tailrec", "vararg", "where",
    ];
    if KEYWORDS.contains(&s) {
        format!("`{s}`")
    } else {
        s.to_string()
    }
}

/// Field name: Rust snake_case -> Kotlin lowerCamelCase (keywords escaped).
fn kotlin_field(name: &str) -> String {
    kotlin_ident(&camel(name))
}

/// Enum variant: Rust PascalCase -> Kotlin UPPER_SNAKE_CASE, keeping acronyms readable
/// (`Red` -> `RED`, `URL` -> `URL`, `HTTPServer` -> `HTTP_SERVER`).
fn kotlin_variant(name: &str) -> String {
    let chars: Vec<char> = name.chars().collect();
    let mut out = String::new();
    for (i, &c) in chars.iter().enumerate() {
        if c.is_uppercase() && i > 0 {
            let prev = chars[i - 1];
            let next = chars.get(i + 1).copied();
            if prev.is_lowercase() || prev.is_ascii_digit() || next.is_some_and(|n| n.is_lowercase()) {
                out.push('_');
            }
        }
        out.extend(c.to_uppercase());
    }
    out
}

/// Owned (plain data class) scalar type.
fn kotlin_scalar(s: SimpleType) -> &'static str {
    match s {
        SimpleType::Bool => "Boolean",
        SimpleType::U8 => "UByte",
        SimpleType::I8 => "Byte",
        SimpleType::U16 => "UShort",
        SimpleType::I16 => "Short",
        SimpleType::U32 => "UInt",
        SimpleType::I32 => "Int",
        SimpleType::U64 => "ULong",
        SimpleType::I64 => "Long",
        SimpleType::F32 => "Float",
        SimpleType::F64 => "Double",
        SimpleType::String | SimpleType::Bytes => unreachable!("slot-shaped types are not scalars"),
    }
}

/// `RawMessage` read method for a scalar.
fn read_fn(s: SimpleType) -> &'static str {
    match s {
        SimpleType::Bool => "readBool",
        SimpleType::U8 => "readU8",
        SimpleType::I8 => "readI8",
        SimpleType::U16 => "readU16",
        SimpleType::I16 => "readI16",
        SimpleType::U32 => "readU32",
        SimpleType::I32 => "readI32",
        SimpleType::U64 => "readU64",
        SimpleType::I64 => "readI64",
        SimpleType::F32 => "readF32",
        SimpleType::F64 => "readF64",
        SimpleType::String | SimpleType::Bytes => unreachable!("slot-shaped types are not scalars"),
    }
}

/// `Writer` method for a scalar (signed 8/16-bit values have writers of their own).
fn write_fn(s: SimpleType) -> &'static str {
    match s {
        SimpleType::Bool => "writeBool",
        SimpleType::U8 => "writeU8",
        SimpleType::I8 => "writeI8",
        SimpleType::U16 => "writeU16",
        SimpleType::I16 => "writeI16",
        SimpleType::U32 => "writeU32",
        SimpleType::I32 => "writeI32",
        SimpleType::U64 => "writeU64",
        SimpleType::I64 => "writeI64",
        SimpleType::F32 => "writeF32",
        SimpleType::F64 => "writeF64",
        SimpleType::String | SimpleType::Bytes => unreachable!("slot-shaped types are not scalars"),
    }
}

/// The `MessageScalar` constant that reads a scalar (enums pass their companion instead).
fn scalar_const(s: SimpleType) -> String {
    format!(
        "MessageScalar.{}",
        match s {
            SimpleType::Bool => "BOOL",
            SimpleType::U8 => "U8",
            SimpleType::I8 => "I8",
            SimpleType::U16 => "U16",
            SimpleType::I16 => "I16",
            SimpleType::U32 => "U32",
            SimpleType::I32 => "I32",
            SimpleType::U64 => "U64",
            SimpleType::I64 => "I64",
            SimpleType::F32 => "F32",
            SimpleType::F64 => "F64",
            SimpleType::String | SimpleType::Bytes => unreachable!("slot-shaped types are not scalars"),
        }
    )
}

/// Zero literal of a scalar, for extension-block fields an older writer left out.
fn zero_lit(s: SimpleType) -> &'static str {
    match s {
        SimpleType::Bool => "false",
        SimpleType::U8 | SimpleType::U16 | SimpleType::U32 => "0u",
        SimpleType::U64 => "0uL",
        SimpleType::I8 | SimpleType::I16 | SimpleType::I32 | SimpleType::I64 => "0",
        SimpleType::F32 => "0.0f",
        SimpleType::F64 => "0.0",
        SimpleType::String | SimpleType::Bytes => unreachable!("slot-shaped types are not scalars"),
    }
}

/// Owned (plain data class) type.
fn kotlin_owned_ty(ty: &Type) -> String {
    match ty {
        Type::Simple(SimpleType::String) => "String".into(),
        Type::Simple(SimpleType::Bytes) => "ByteArray".into(),
        Type::Simple(s) => kotlin_scalar(*s).into(),
        Type::Enum { name } | Type::Struct { name } => name.clone(),
        Type::Array { body } => format!("List<{}>", kotlin_owned_ty(&body.elem)),
        Type::Map { body } => {
            format!("Map<{}, {}>", kotlin_owned_ty(&body.key), kotlin_owned_ty(&body.value))
        }
    }
}

/// Reader-side type of a field value.
fn kotlin_reader_ty(ty: &Type) -> String {
    match ty {
        Type::Simple(SimpleType::String) => "String".into(),
        Type::Simple(SimpleType::Bytes) => "ByteArray".into(),
        Type::Simple(s) => kotlin_scalar(*s).into(),
        Type::Enum { name } => name.clone(),
        Type::Struct { name } => format!("{name}Reader"),
        Type::Array { body } => view_ty(&body.elem),
        Type::Map { .. } => unreachable!("maps are handled at the field level"),
    }
}

/// View type for array elements.
fn view_ty(elem: &Type) -> String {
    match elem {
        Type::Simple(SimpleType::String) => "StringListView".into(),
        Type::Simple(SimpleType::Bytes) => "BytesListView".into(),
        Type::Simple(s) => format!("ScalarListView<{}>", kotlin_scalar(*s)),
        Type::Enum { name } => format!("ScalarListView<{name}>"),
        Type::Struct { name } => format!("StructEvoListView<{name}Reader>"),
        Type::Array { .. } => "SlotListView".into(),
        Type::Map { .. } => unreachable!("maps cannot be array elements"),
    }
}

/// View construction over elements of `elem` at payload position `start` with `count` elements
/// (`msg` is the RawMessage in scope at every place the generator emits a view).
fn view_ctor(elem: &Type, start: &str, count: &str, set: &SchemaSet) -> String {
    match elem {
        Type::Simple(SimpleType::String) => format!("StringListView(msg, {start}, {count})"),
        Type::Simple(SimpleType::Bytes) => format!("BytesListView(msg, {start}, {count})"),
        Type::Simple(s) => format!("ScalarListView(msg, {start}, {count}, {})", scalar_const(*s)),
        Type::Enum { name } => format!("ScalarListView(msg, {start}, {count}, {name})"),
        Type::Struct { name } => format!(
            "StructEvoListView(msg, {start}, ({count}).toLong(), {}) {{ m, p, e, h -> {name}Reader(m, p, e, h) }}",
            element_size(elem, set).expect("element size of a planned schema")
        ),
        Type::Array { .. } => format!("SlotListView(msg, {start}, {count})"),
        Type::Map { .. } => unreachable!("maps cannot be array elements"),
    }
}

/// Whether struct `name` has extension blocks: containers of it are then written in instance
/// mode (per-element / per-value slots, shape bit set).
fn has_ext(set: &SchemaSet, name: &str) -> bool {
    set.message(name).is_some_and(|m| !m.layout.ext_blocks.is_empty())
}

fn fixed_len_of(set: &SchemaSet, name: &str) -> usize {
    set.message(name).map(|m| m.layout.fixed_len).expect("planned struct")
}

fn is_scalar(t: &Type) -> bool {
    matches!(t, Type::Simple(s) if s.is_scalar())
}

/// Whether a field's type holds bytes inside arrays / maps (its data class then compares them by
/// content; nested structs take care of themselves).
fn contains_bytes(ty: &Type) -> bool {
    match ty {
        Type::Simple(SimpleType::Bytes) => true,
        Type::Array { body } => contains_bytes(&body.elem),
        Type::Map { body } => contains_bytes(&body.key) || contains_bytes(&body.value),
        _ => false,
    }
}

// ---------- Enums ----------

fn write_enum(out: &mut String, e: &EnumDescriptor) {
    let _ = writeln!(out, "enum class {}(override val value: Int) : MessageEnum {{", e.name);
    let last = e.variants.len().saturating_sub(1);
    for (i, v) in e.variants.iter().enumerate() {
        let end = if i == last { ";" } else { "," };
        let _ = writeln!(out, "    {}({}){end}", kotlin_variant(&v.name), v.value);
    }
    let _ = writeln!(out, "");
    let _ = writeln!(out, "    companion object : MessageEnumCompanion<{}> {{", e.name);
    let _ = writeln!(out, "        override val enumName = \"{}\"", e.name);
    let _ = writeln!(out, "        override fun fromValue(v: Int): {}? = entries.firstOrNull {{ it.value == v }}", e.name);
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "}}\n");
}

// ---------- Reader ----------

/// Expression reading a value of `ty` at absolute payload position `pos`.
fn read_expr(ty: &Type, pos: &str, set: &SchemaSet) -> String {
    read_expr_hv(ty, pos, "hv", set)
}

/// Same, with the header version passed to nested struct readers (elements and map values get 0).
fn read_expr_hv(ty: &Type, pos: &str, hv: &str, set: &SchemaSet) -> String {
    match ty {
        Type::Simple(SimpleType::String) => format!("msg.readString({pos})"),
        Type::Simple(SimpleType::Bytes) => format!("msg.readBytes({pos})"),
        Type::Simple(s) => format!("msg.{}({pos})", read_fn(*s)),
        Type::Enum { name } => format!("{name}.read(msg, {pos})"),
        Type::Struct { name } => {
            let _ = hv;
            format!("msg.readSlot({pos}).let {{ s -> {name}Reader(msg, s.offset.toInt(), (s.offset + s.length).toInt(), INSTANCE_HV) }}")
        }
        Type::Array { body } => {
            if body.fixed.is_some() && !body.elem.is_slot_shaped() {
                view_ctor(&body.elem, pos, &body.fixed.unwrap().to_string(), set)
            } else {
                format!("msg.viewAt({pos}) {{ o, n -> {} }}", view_ctor(&body.elem, "o", "n", set))
            }
        }
        Type::Map { .. } => unreachable!("maps are handled at the field level"),
    }
}

/// Reader-side type of a field (maps get their generated view type).
fn reader_ret_ty(f: &FieldDescriptor) -> String {
    match &f.ty {
        Type::Map { .. } => format!("{}MapView", pascal(&f.name)),
        ty => kotlin_reader_ty(ty),
    }
}

/// Expression reading field `f` at absolute payload position `pos`.
fn read_field_expr(f: &FieldDescriptor, pos: &str, set: &SchemaSet) -> String {
    match &f.ty {
        Type::Map { .. } => {
            format!("msg.viewAt({pos}) {{ o, n -> {}MapView(msg, o, n) }}", pascal(&f.name))
        }
        ty => read_expr(ty, pos, set),
    }
}

/// Value returned for a required extension-block field when the writer's schema predates it.
fn default_expr(ty: &Type, field: &str, set: &SchemaSet) -> String {
    match ty {
        Type::Simple(SimpleType::Bool) => "false".into(),
        Type::Simple(SimpleType::String) => "\"\"".into(),
        Type::Simple(SimpleType::Bytes) => "ByteArray(0)".into(),
        Type::Simple(s) => zero_lit(*s).into(),
        Type::Enum { .. } | Type::Struct { .. } => format!(
            "throw IllegalStateException(\"field `{field}` missing: data written by an older schema version\")"
        ),
        Type::Array { body } => view_ctor(&body.elem, "0", "0", set),
        Type::Map { .. } => format!("{}MapView(msg, 0, 0)", pascal(field)),
    }
}

/// Expression turning the reader value `expr` of `ty` into its owned form.
fn owned_expr(ty: &Type, expr: &str, set: &SchemaSet) -> String {
    match ty {
        Type::Simple(_) | Type::Enum { .. } => expr.to_string(),
        Type::Struct { .. } => format!("{expr}.toOwned()"),
        Type::Array { body } => owned_list(&body.elem, expr, set, 0),
        Type::Map { .. } => unreachable!("maps are handled at the field level"),
    }
}

/// `expr` is a view over elements of `elem`; nested dynamic arrays (`SlotListView`) yield slots,
/// so each inner view is rebuilt from its slot before recursing.
fn owned_list(elem: &Type, expr: &str, set: &SchemaSet, depth: usize) -> String {
    match elem {
        Type::Simple(_) | Type::Enum { .. } => format!("{expr}.toList()"),
        Type::Struct { .. } => format!("{expr}.map {{ it.toOwned() }}"),
        Type::Array { body } => {
            let s = format!("s{depth}");
            let inner_view =
                view_ctor(&body.elem, &format!("{s}.offset.toInt()"), &format!("{s}.length.toInt()"), set);
            format!("{expr}.map {{ {s} -> {} }}", owned_list(&body.elem, &inner_view, set, depth + 1))
        }
        Type::Map { .. } => unreachable!(),
    }
}

/// `expr` for a map field of `f`: the lazy entries collected into a `Map`.
fn owned_map_expr(f: &FieldDescriptor, expr: &str, set: &SchemaSet) -> String {
    let Type::Map { body } = &f.ty else { unreachable!("owned_map_expr on a non-map") };
    let value = owned_expr(&body.value, "it.value", set);
    format!("{expr}.associate {{ it.key to {value} }}")
}

/// Constructor argument of `toOwned()` for one field.
fn owned_arg(f: &FieldDescriptor, set: &SchemaSet) -> String {
    let fname = kotlin_field(&f.name);
    let expr = match &f.ty {
        Type::Map { .. } => owned_map_expr(f, &fname, set),
        ty => owned_expr(ty, &fname, set),
    };
    format!("{fname} = {expr}")
}

fn write_reader(out: &mut String, m: &MessageDescriptor, set: &SchemaSet) {
    let name = &m.name;
    let ext_versions =
        m.layout.ext_blocks.iter().map(|b| b.version.to_string()).collect::<Vec<_>>().join(", ");
    let _ = writeln!(out, "class {name}Reader(override val msg: RawMessage, override val origin: Int, override val end: Int, override val hv: Int) : MessageReader {{");
    for f in &m.fields {
        if f.reserved {
            continue;
        }
        let fname = kotlin_field(&f.name);
        let ret = reader_ret_ty(f);
        let bit = f.optional_bit.unwrap_or(0);
        if f.since > 1 {
            let since = f.since;
            let min_len = m.layout.ext_blocks.iter().find(|b| b.version == since).map_or(0, |b| b.fixed_len);
            let find = format!("val bs = msg.findExtBlock(EXT_VERSIONS, hv, {since}, {min_len}, origin, end)");
            if f.optional {
                line(out, 1, &format!("val {fname}: {ret}?"));
                line(out, 2, "get() {");
                line(out, 3, &format!("{find} ?: return null"));
                let read = read_field_expr(f, &format!("bs + {}", f.offset), set);
                line(out, 3, &format!("return if (msg.bitmapBit(bs, {bit})) {read} else null"));
                line(out, 2, "}");
            } else {
                line(out, 1, &format!("val {fname}: {ret}"));
                line(out, 2, "get() {");
                line(out, 3, &format!("{find} ?: return {}", default_expr(&f.ty, &fname, set)));
                line(out, 3, &format!("return {}", read_field_expr(f, &format!("bs + {}", f.offset), set)));
                line(out, 2, "}");
            }
        } else if f.optional {
            line(out, 1, &format!("val {fname}: {ret}?"));
            line(out, 2, &format!("get() = if (msg.bitmapBit(origin, {bit})) {} else null", read_field_expr(f, &format!("origin + {}", f.offset), set)));
        } else {
            line(out, 1, &format!("val {fname}: {ret} get() = {}", read_field_expr(f, &format!("origin + {}", f.offset), set)));
        }
    }

    line(out, 1, "");
    line(out, 1, &format!("fun toOwned(): {name} = {name}("));
    for f in m.fields.iter().filter(|f| !f.reserved) {
        line(out, 2, &format!("{},", owned_arg(f, set)));
    }
    line(out, 1, ")");

    line(out, 1, "");
    line(out, 1, "companion object {");
    line(out, 2, &format!("val KEY: UInt = {}u", m.key));
    line(out, 2, &format!("const val FIXED_LEN = {}", m.layout.fixed_len));
    line(out, 2, &format!("val EXT_VERSIONS = intArrayOf({ext_versions})"));
    line(out, 2, "");
    line(out, 2, "/// Lazy decode: null only when the buffer is too short or the key does not match.");
    line(out, 2, &format!("fun decode(bytes: ByteArray): {name}Reader? {{"));
    line(out, 3, "val m = RawMessage.decode(bytes, KEY, FIXED_LEN) ?: return null");
    line(out, 3, &format!("return {name}Reader(m, 0, m.payloadSize, m.version)"));
    line(out, 2, "}");
    line(out, 1, "}");
    let _ = writeln!(out, "}}\n");
}

fn write_map_views(out: &mut String, m: &MessageDescriptor, set: &SchemaSet) {
    for f in &m.fields {
        if f.reserved {
            continue;
        }
        let Type::Map { body } = &f.ty else { continue };
        let view = format!("{}MapView", pascal(&f.name));
        let l = message_core::map_entry_layouts(&body.key, &body.value, set).expect("planned map");
        let key_ty = kotlin_reader_ty(&body.key);
        let val_ty = kotlin_reader_ty(&body.value);
        let entry_ty = format!("Map.Entry<{key_ty}, {val_ty}>");
        let key_read = read_expr_hv(&body.key, "start + i * stride", "0", set);
        // Struct values: the writer's shape bit selects open entries (value = fixed region) or
        // instance entries (value = slot to a self-contained instance).
        let (stride, v_off, val_read) = match body.value.as_ref() {
            Type::Struct { name } => (
                format!("if (inst) {} else {}", l.inst_stride, l.open_stride),
                format!("if (inst) {} else {}", l.inst_value_offset, l.open_value_offset),
                format!(
                    "val p = start + i * stride + vOff\n        if (inst) return msg.readSlot(p).let {{ s -> {name}Reader(msg, s.offset.toInt(), (s.offset + s.length).toInt(), INSTANCE_HV) }}\n        return {name}Reader(msg, p, msg.payloadSize, 0)"
                ),
            ),
            _ => (
                l.open_stride.to_string(),
                l.open_value_offset.to_string(),
                format!("return {}", read_expr_hv(&body.value, "start + i * stride + vOff", "0", set)),
            ),
        };
        let _ = writeln!(out, "class {view}(val msg: RawMessage, val start: Int, private val rawLen: Int) : AbstractList<{entry_ty}>() {{");
        let _ = writeln!(out, "    override val size: Int get() = rawLen and LEN_MASK");
        let _ = writeln!(out, "    private val inst: Boolean get() = (rawLen and SHAPE_BIT) != 0");
        let _ = writeln!(out, "    private val stride: Int get() = {stride}");
        let _ = writeln!(out, "    private val vOff: Int get() = {v_off}");
        let _ = writeln!(out, "    override fun get(index: Int): {entry_ty} = entry(index)");
        let _ = writeln!(out, "    fun key(i: Int): {key_ty} {{");
        let _ = writeln!(out, "        checkIndex(i, size)");
        let _ = writeln!(out, "        return {key_read}");
        let _ = writeln!(out, "    }}");
        let _ = writeln!(out, "    fun value(i: Int): {val_ty} {{");
        let _ = writeln!(out, "        checkIndex(i, size)");
        let _ = writeln!(out, "        {val_read}");
        let _ = writeln!(out, "    }}");
        let _ = writeln!(out, "    fun entry(i: Int): {entry_ty} = MapEntry(key(i), value(i))");
        let _ = writeln!(out, "}}\n");
    }
}

// ---------- Owned data class ----------

fn write_owned_struct(out: &mut String, m: &MessageDescriptor) {
    let name = &m.name;
    let _ = writeln!(out, "data class {name}(");
    for f in m.fields.iter().filter(|f| !f.reserved) {
        let ty = kotlin_owned_ty(&f.ty);
        let ty = if f.optional { format!("{ty}?") } else { ty };
        let _ = writeln!(out, "    val {}: {ty},", kotlin_field(&f.name));
    }
    let _ = writeln!(out, ") {{");
    let fields: Vec<&FieldDescriptor> = m.fields.iter().filter(|f| !f.reserved).collect();
    if fields.iter().any(|f| contains_bytes(&f.ty)) {
        let _ = writeln!(out, "    override fun equals(other: Any?): Boolean =");
        let _ = writeln!(out, "        other is {name} &&");
        for (i, f) in fields.iter().enumerate() {
            let fname = kotlin_field(&f.name);
            let cmp = if contains_bytes(&f.ty) {
                format!("contentEquals({fname}, other.{fname})")
            } else {
                format!("{fname} == other.{fname}")
            };
            let _ = writeln!(out, "            {cmp}{}", if i + 1 < fields.len() { " &&" } else { "" });
        }
        let _ = writeln!(out, "");
        let _ = writeln!(out, "    override fun hashCode(): Int {{");
        for (i, f) in fields.iter().enumerate() {
            let fname = kotlin_field(&f.name);
            let h = if contains_bytes(&f.ty) { format!("contentHashCode({fname})") } else { format!("{fname}.hashCode()") };
            if i == 0 {
                let _ = writeln!(out, "        var h = {h}");
            } else {
                let _ = writeln!(out, "        h = 31 * h + {h}");
            }
        }
        let _ = writeln!(out, "        return h");
        let _ = writeln!(out, "    }}");
        let _ = writeln!(out, "");
    }
}

// ---------- Encoder ----------

/// `private fun __writeXxxBase(w: Writer, base: Int, value: Xxx)`: the base fields of a struct
/// at an already reserved position (inline fields, struct elements, map values).
fn write_base_writer(out: &mut String, m: &MessageDescriptor, set: &SchemaSet) {
    let _ = writeln!(out, "private fun __write{}Base(w: Writer, base: Int, value: {}) {{", m.name, m.name);
    for f in m.fields.iter().filter(|f| f.since == 1) {
        write_field(out, 1, f, &format!("value.{}", kotlin_field(&f.name)), "base", set);
    }
    let _ = writeln!(out, "}}\n");
    if !m.layout.ext_blocks.is_empty() {
        // the extension chain, appended after the base var data (top-level message or instance)
        let _ = writeln!(out, "private fun __write{}Ext(w: Writer, value: {}) {{", m.name, m.name);
        for b in &m.layout.ext_blocks {
            line(out, 1, "run {");
            line(out, 2, &format!("val blk = w.reserve({})", b.fixed_len));
            for f in m.fields.iter().filter(|f| f.since == b.version) {
                write_field(out, 2, f, &format!("value.{}", kotlin_field(&f.name)), "blk", set);
            }
            line(out, 2, &format!("w.writeTrailer(blk, {})", b.version));
            line(out, 1, "}");
        }
        let _ = writeln!(out, "}}\n");
    }
    // self-contained instance: fixed region, own var data, extension chain; returns its start
    let _ = writeln!(out, "private fun __write{}Instance(w: Writer, value: {}): Int {{", m.name, m.name);
    line(out, 1, &format!("val s = w.reserve({})", m.layout.fixed_len));
    line(out, 1, &format!("__write{}Base(w, s, value)", m.name));
    if !m.layout.ext_blocks.is_empty() {
        line(out, 1, &format!("__write{}Ext(w, value)", m.name));
    }
    line(out, 1, "return s");
    let _ = writeln!(out, "}}\n");
}

/// `fun encode(): ByteArray`: header + base + extension blocks, all with literal offsets.
fn write_encode(out: &mut String, m: &MessageDescriptor, set: &SchemaSet) {
    let need = 8 + m.layout.fixed_len;
    let max_version = m.layout.ext_blocks.last().map_or(0, |b| b.version);
    line(out, 1, "/// Canonical encoding (byte-identical to Rust and TypeScript): declaration-order var data, sorted map keys.");
    line(out, 1, "fun encode(): ByteArray {");
    line(out, 2, &format!("val w = Writer({need})"));
    line(out, 2, "w.reserve(8)");
    line(out, 2, &format!("val base = w.reserve({})", m.layout.fixed_len));
    line(out, 2, &format!("__write{}Base(w, base, this)", m.name));
    if !m.layout.ext_blocks.is_empty() {
        line(out, 2, &format!("__write{}Ext(w, this)", m.name));
    }
    let _ = set;
    line(out, 2, &format!("w.writeU32(0, {}Reader.KEY)", m.name));
    line(out, 2, &format!("w.writeU16(4, {}u)", m.layout.fixed_len));
    line(out, 2, &format!("w.writeU8(6, {max_version}u)"));
    line(out, 2, "w.writeU8(7, 0u)");
    line(out, 2, "return w.finish()");
    line(out, 1, "}");
}

/// Write one field of a block: optional fields set their bitmap bit, reserved fields stay zero.
fn write_field(out: &mut String, level: usize, f: &FieldDescriptor, val: &str, block: &str, set: &SchemaSet) {
    if f.reserved {
        return;
    }
    let pos = format!("{block} + {}", f.offset);
    if f.optional {
        line(out, level, &format!("{val}?.let {{ v ->"));
        line(out, level + 1, &format!("w.setBit({block}, {})", f.optional_bit.unwrap_or(0)));
        write_value_or_map(out, level + 1, f, &f.ty, "v", &pos, set);
        line(out, level, "}");
    } else {
        write_value_or_map(out, level, f, &f.ty, val, &pos, set);
    }
}

fn write_value_or_map(out: &mut String, level: usize, f: &FieldDescriptor, ty: &Type, val: &str, pos: &str, set: &SchemaSet) {
    match ty {
        Type::Map { .. } => write_map_field(out, level, f, val, pos, set),
        _ => write_value(out, level, ty, val, pos, set, 0),
    }
}

fn write_value(out: &mut String, level: usize, ty: &Type, val: &str, pos: &str, set: &SchemaSet, depth: usize) {
    match ty {
        Type::Simple(SimpleType::String) => line(out, level, &format!("w.writeStringSlot({pos}, {val})")),
        Type::Simple(SimpleType::Bytes) => line(out, level, &format!("w.writeBytesSlot({pos}, {val})")),
        Type::Simple(s) => line(out, level, &format!("w.{}({pos}, {val})", write_fn(*s))),
        Type::Enum { .. } => line(out, level, &format!("w.writeI32({pos}, {val}.value)")),
        Type::Struct { name } => {
            line(out, level, &format!("run {{ val s = __write{name}Instance(w, {val}); w.writeSlot({pos}, w.rel(s), w.length - s) }}"));
        }
        Type::Array { body } if matches!(body.elem.as_ref(), Type::Struct { name } if has_ext(set, name)) => {
            // elements with extension fields: per-element instance slots, shape bit set
            let Type::Struct { name } = body.elem.as_ref() else { unreachable!() };
            let (a, i, r) = (format!("a{depth}"), format!("i{depth}"), format!("r{depth}"));
            line(out, level, "run {");
            line(out, level + 1, &format!("val {a} = {val}"));
            line(out, level + 1, &format!("val {r} = w.reserve({a}.size * 8)"));
            line(out, level + 1, &format!("for ({i} in {a}.indices) {{"));
            line(out, level + 2, &format!("val s = __write{name}Instance(w, {a}[{i}])"));
            line(out, level + 2, &format!("w.writeSlot({r} + {i} * 8, w.rel(s), w.length - s)"));
            line(out, level + 1, "}");
            line(out, level + 1, &format!("w.writeSlot({pos}, w.rel({r}), {a}.size or SHAPE_BIT)"));
            line(out, level, "}");
        }
        Type::Array { body } => {
            let w = element_size(&body.elem, set).expect("element size of a planned schema");
            let (a, i, r) = (format!("a{depth}"), format!("i{depth}"), format!("r{depth}"));
            if body.fixed.is_some() && !body.elem.is_slot_shaped() {
                line(out, level, &format!("for ({i} in 0 until minOf({}, {val}.size)) {{", body.fixed.unwrap()));
                write_open_elem(out, level + 1, &body.elem, &format!("{val}[{i}]"), &format!("{pos} + {i} * {w}"), set, depth + 1);
                line(out, level, "}");
            } else {
                line(out, level, "run {");
                line(out, level + 1, &format!("val {a} = {val}"));
                line(out, level + 1, &format!("val {r} = w.reserve({a}.size * {w})"));
                line(out, level + 1, &format!("for ({i} in {a}.indices) {{"));
                write_open_elem(out, level + 2, &body.elem, &format!("{a}[{i}]"), &format!("{r} + {i} * {w}"), set, depth + 1);
                line(out, level + 1, "}");
                line(out, level + 1, &format!("w.writeSlot({pos}, w.rel({r}), {a}.size)"));
                line(out, level, "}");
            }
        }
        Type::Map { .. } => unreachable!("maps are written by write_map_field"),
    }
}

/// An element of a shape=0 (open) array or an unevolved map value: struct elements are written as
/// their fixed-region footprint at `pos` (their var data appended), everything else as a value.
fn write_open_elem(out: &mut String, level: usize, ty: &Type, val: &str, pos: &str, set: &SchemaSet, depth: usize) {
    match ty {
        Type::Struct { name } => line(out, level, &format!("__write{name}Base(w, {pos}, {val})")),
        _ => write_value(out, level, ty, val, pos, set, depth),
    }
}

/// A map field: entries sorted by the key's wire value.
fn write_map_field(out: &mut String, level: usize, f: &FieldDescriptor, val: &str, pos: &str, set: &SchemaSet) {
    let Type::Map { body } = &f.ty else { unreachable!("write_map_field on a non-map") };
    let stride = f.element_size.expect("planned stride");
    let v_off = f.map_value_offset.expect("planned value offset");
    let sort = match body.key.as_ref() {
        Type::Simple(SimpleType::String) => "o.keys.sortedWith(UTF8_STRING_ORDER)".to_string(),
        Type::Simple(SimpleType::Bool) => "o.keys.sortedBy { if (it) 1 else 0 }".to_string(),
        Type::Enum { .. } => "o.keys.sortedBy { it.value }".to_string(),
        Type::Simple(_) => "o.keys.sorted()".to_string(),
        _ => unreachable!("invalid map key rejected by the planner"),
    };
    let key_write = match body.key.as_ref() {
        Type::Simple(SimpleType::String) => "w.writeStringSlot(e, ks[i])".to_string(),
        Type::Enum { .. } => "w.writeI32(e, ks[i].value)".to_string(),
        Type::Simple(s) => format!("w.{}(e, ks[i])", write_fn(*s)),
        _ => unreachable!("invalid map key rejected by the planner"),
    };
    line(out, level, "run {");
    line(out, level + 1, &format!("val o = {val}"));
    line(out, level + 1, &format!("val ks = {sort}"));
    line(out, level + 1, &format!("val r = w.reserve(ks.size * {stride})"));
    line(out, level + 1, "for (i in ks.indices) {");
    line(out, level + 2, &format!("val e = r + i * {stride}"));
    line(out, level + 2, &key_write);
    let instances = matches!(body.value.as_ref(), Type::Struct { name } if has_ext(set, name));
    if instances {
        write_value(out, level + 2, &body.value, "o.getValue(ks[i])", &format!("e + {v_off}"), set, 0);
    } else {
        write_open_elem(out, level + 2, &body.value, "o.getValue(ks[i])", &format!("e + {v_off}"), set, 0);
    }
    line(out, level + 1, "}");
    let len = if instances { "ks.size or SHAPE_BIT" } else { "ks.size" };
    line(out, level + 1, &format!("w.writeSlot({pos}, w.rel(r), {len})"));
    line(out, level, "}");
}

// ---------- Validator ----------

fn write_validators(out: &mut String, m: &MessageDescriptor, set: &SchemaSet) {
    let _ = writeln!(out, "private fun __validate{}Base(m: RawMessage, base: Int, hv: Int) {{", m.name);
    for f in m.fields.iter().filter(|f| f.since == 1) {
        validate_field(out, f, "base", set);
    }
    let _ = writeln!(out, "}}\n");
    for b in &m.layout.ext_blocks {
        let _ = writeln!(out, "private fun __validate{}V{}(m: RawMessage, base: Int, hv: Int) {{", m.name, b.version);
        for f in m.fields.iter().filter(|f| f.since == b.version) {
            validate_field(out, f, "base", set);
        }
        let _ = writeln!(out, "}}\n");
    }
    // self-contained instance in [lo, hi): base, then every extension block the chain offers
    // (no version is promised inside an instance, so absent blocks are legal)
    if m.layout.ext_blocks.is_empty() {
        let _ = writeln!(out, "@Suppress(\"UNUSED_PARAMETER\")");
    }
    let _ = writeln!(out, "private fun __validate{}Inst(m: RawMessage, lo: Int, hi: Int) {{", m.name);
    line(out, 1, &format!("__validate{}Base(m, lo, INSTANCE_HV)", m.name));
    for b in m.layout.ext_blocks.iter().rev() {
        let v = b.version;
        line(out, 1, &format!(
            "m.findExtBlock({name}Reader.EXT_VERSIONS, INSTANCE_HV, {v}, {fixed}, lo, hi)?.let {{ __validate{name}V{v}(m, it, INSTANCE_HV) }}",
            name = m.name,
            fixed = b.fixed_len
        ));
    }
    let _ = writeln!(out, "}}\n");
}

fn write_validate(out: &mut String, m: &MessageDescriptor) {
    let r = format!("{}Reader", m.name);
    line(out, 2, "/// Strictly check an untrusted buffer; after null no accessor can throw on it.");
    line(out, 2, "fun validate(bytes: ByteArray): ValidationError? = runValidation {");
    line(out, 3, &format!("val m = RawMessage.validating(bytes, {r}.KEY, {r}.FIXED_LEN)"));
    line(out, 3, &format!("__validate{}Base(m, 0, m.version)", m.name));
    for b in m.layout.ext_blocks.iter().rev() {
        let v = b.version;
        line(out, 3, &format!("if (m.version >= {v}) {{"));
        line(out, 4, &format!("__validate{}V{v}(m, checkExtBlock(m, {r}.EXT_VERSIONS, m.version, {v}, {}), m.version)", m.name, b.fixed_len));
        line(out, 3, "}");
    }
    line(out, 2, "}");
}

/// Statement checking one field (optional fields only when their bitmap bit is set).
fn validate_field(out: &mut String, f: &FieldDescriptor, block: &str, set: &SchemaSet) {
    if f.reserved {
        return;
    }
    let pos = format!("{block} + {}", f.offset);
    let field = kotlin_field(&f.name);
    let bit = f.optional_bit.unwrap_or(0);
    let level = if f.optional { 2 } else { 1 };
    // the bitmap guard is only emitted when there is something to check
    let guard = |out: &mut String, open: bool| {
        if f.optional {
            let s = if open { format!("if (m.bitmapBit({block}, {bit})) {{") } else { "}".to_string() };
            line(out, 1, &s);
        }
    };
    match &f.ty {
        // arrays and maps locate their own errors (region + per element)
        Type::Array { .. } | Type::Map { .. } => {
            let body = validate_body(&f.ty, &pos, &field, f, set, 0, None);
            if body.is_empty() {
                return;
            }
            guard(out, true);
            if body.len() == 1 && body[0].0 == 0 {
                line(out, level, &body[0].1);
            } else {
                line(out, level, "run {");
                emit(out, level + 1, &body);
                line(out, level, "}");
            }
            guard(out, false);
        }
        _ => {
            let Some(leaf) = leaf_stmt(&f.ty, &pos) else { return };
            guard(out, true);
            emit_nested(out, level, &field, None, &leaf);
            guard(out, false);
        }
    }
}

/// Bare check statement for a leaf-shaped value (scalars need nothing).
fn leaf_stmt(ty: &Type, pos: &str) -> Option<String> {
    match ty {
        Type::Simple(SimpleType::String) => Some(format!("checkStrSlot(m, {pos})")),
        Type::Simple(SimpleType::Bytes) => Some(format!("checkBytesSlot(m, {pos})")),
        Type::Simple(_) => None,
        Type::Enum { name } => Some(format!("checkEnum({name}, m, {pos})")),
        Type::Struct { name } => Some(format!("checkInstance(m, {pos}).let {{ __validate{name}Inst(m, it.lo, it.hi) }}")),
        _ => unreachable!("arrays and maps are handled by validate_body"),
    }
}

/// `nest("field"[, index]) { leaf }`.
fn emit_nested(out: &mut String, level: usize, field: &str, index: Option<&str>, leaf: &str) {
    match index {
        Some(i) => line(out, level, &format!("nest(\"{field}\", {i}) {{ {leaf} }}")),
        None => line(out, level, &format!("nest(\"{field}\") {{ {leaf} }}")),
    }
}

/// Statements checking an array or map at `pos`: region failures are located by the labelled
/// `checkRegion`, element failures by `nest`. `idx` is the index of the enclosing element
/// (nested arrays), `depth` keeps loop variables unique.
fn validate_body(ty: &Type, pos: &str, field: &str, f: &FieldDescriptor, set: &SchemaSet, depth: usize, idx: Option<&str>) -> Lines {
    let mut out: Lines = Vec::new();
    let idx_arg = idx.map(|i| format!(", {i}")).unwrap_or_default();
    match ty {
        Type::Array { body } => {
            let w = element_size(&body.elem, set).expect("element size of a planned schema");
            if body.fixed.is_some() && !body.elem.is_slot_shaped() {
                let i = format!("i{depth}");
                if let Some(leaf) = leaf_stmt(&body.elem, &format!("{pos} + {i} * {w}")) {
                    out.push((0, format!("for ({i} in 0 until {}) {{", body.fixed.unwrap())));
                    out.push((1, format!("nest(\"{field}\", {i}) {{ {leaf} }}")));
                    out.push((0, "}".into()));
                }
            } else if let Type::Struct { name } = body.elem.as_ref() {
                // the writer's shape bit selects open footprints vs instance slots
                let fixed = fixed_len_of(set, name);
                let (r, i) = (format!("r{depth}"), format!("i{depth}"));
                out.push((0, format!("val {r} = checkRegionShape(m, {pos}, \"{field}\"{idx_arg})")));
                out.push((0, format!("if ({r}.instances) {{")));
                out.push((1, format!("for ({i} in 0 until {r}.count) {{")));
                out.push((2, format!("nest(\"{field}\", {i}) {{ checkInstance(m, {r}.offset + {i} * 8).let {{ __validate{name}Inst(m, it.lo, it.hi) }} }}")));
                out.push((1, "}".into()));
                out.push((0, "} else {".into()));
                out.push((1, format!("checkExtent(m, {r}.offset, {r}.count, {fixed}, \"{field}\"{idx_arg})")));
                out.push((1, format!("for ({i} in 0 until {r}.count) {{")));
                out.push((2, format!("nest(\"{field}\", {i}) {{ __validate{name}Base(m, {r}.offset + {i} * {fixed}, 0) }}")));
                out.push((1, "}".into()));
                out.push((0, "}".into()));
            } else if is_scalar(&body.elem) {
                out.push((0, format!("checkRegion(m, {pos}, {w}, \"{field}\"{idx_arg})")));
            } else {
                let (o, n, i) = (format!("o{depth}"), format!("n{depth}"), format!("i{depth}"));
                out.push((0, format!("val ({o}, {n}) = checkRegion(m, {pos}, {w}, \"{field}\"{idx_arg})")));
                out.push((0, format!("for ({i} in 0 until {n}) {{")));
                let elem_pos = format!("{o} + {i} * {w}");
                if let Type::Array { .. } = body.elem.as_ref() {
                    for (l, s) in validate_body(&body.elem, &elem_pos, field, f, set, depth + 1, Some(&i)) {
                        out.push((l + 1, s));
                    }
                } else if let Some(leaf) = leaf_stmt(&body.elem, &elem_pos) {
                    out.push((1, format!("nest(\"{field}\", {i}) {{ {leaf} }}")));
                }
                out.push((0, "}".into()));
            }
        }
        Type::Map { body } => {
            let stride = f.element_size.expect("planned stride");
            let v_off = f.map_value_offset.expect("planned value offset");
            if is_scalar(&body.key) && is_scalar(&body.value) {
                out.push((0, format!("checkRegion(m, {pos}, {stride}, \"{field}\"{idx_arg})")));
                return out;
            }
            let (o, n, i) = (format!("o{depth}"), format!("n{depth}"), format!("i{depth}"));
            if let Type::Struct { name } = body.value.as_ref() {
                // shape bit selects the entry layout: open (value = fixed region) or instance slot
                let l = message_core::map_entry_layouts(&body.key, &body.value, set).expect("planned map");
                let (r, i) = (format!("r{depth}"), format!("i{depth}"));
                out.push((0, format!("val {r} = checkRegionShape(m, {pos}, \"{field}\"{idx_arg})")));
                out.push((0, format!("val st = if ({r}.instances) {} else {}", l.inst_stride, l.open_stride)));
                out.push((0, format!("val vo = if ({r}.instances) {} else {}", l.inst_value_offset, l.open_value_offset)));
                out.push((0, format!("checkExtent(m, {r}.offset, {r}.count, st, \"{field}\"{idx_arg})")));
                out.push((0, format!("for ({i} in 0 until {r}.count) {{")));
                out.push((1, format!("val e = {r}.offset + {i} * st")));
                if let Some(leaf) = leaf_stmt(&body.key, "e") {
                    out.push((1, format!("nest(\"{field}\", {i}) {{ {leaf} }}")));
                }
                out.push((1, format!(
                    "if ({r}.instances) nest(\"{field}\", {i}) {{ checkInstance(m, e + vo).let {{ __validate{name}Inst(m, it.lo, it.hi) }} }}"
                )));
                out.push((1, format!("else nest(\"{field}\", {i}) {{ __validate{name}Base(m, e + vo, 0) }}")));
                out.push((0, "}".into()));
                return out;
            }
            out.push((0, format!("val ({o}, {n}) = checkRegion(m, {pos}, {stride}, \"{field}\"{idx_arg})")));
            out.push((0, format!("for ({i} in 0 until {n}) {{")));
            out.push((1, format!("val e = {o} + {i} * {stride}")));
            if let Some(leaf) = leaf_stmt(&body.key, "e") {
                out.push((1, format!("nest(\"{field}\", {i}) {{ {leaf} }}")));
            }
            let v_pos = format!("e + {v_off}");
            if let Type::Array { .. } = body.value.as_ref() {
                for (l, s) in validate_body(&body.value, &v_pos, field, f, set, depth + 1, Some(&i)) {
                    out.push((l + 1, s));
                }
            } else if let Some(leaf) = leaf_stmt(&body.value, &v_pos) {
                out.push((1, format!("nest(\"{field}\", {i}) {{ {leaf} }}")));
            }
            out.push((0, "}".into()));
        }
        _ => unreachable!("validate_body handles arrays and maps only"),
    }
    out
}

// ---------- Per message ----------

fn write_message(out: &mut String, m: &MessageDescriptor, set: &SchemaSet) {
    let name = &m.name;
    write_reader(out, m, set);
    write_map_views(out, m, set);
    write_owned_struct(out, m);
    write_encode(out, m, set);
    line(out, 1, "");
    line(out, 1, "companion object {");
    line(out, 2, &format!("fun decode(bytes: ByteArray): {name}Reader? = {name}Reader.decode(bytes)"));
    line(out, 2, &format!("fun fromBytes(bytes: ByteArray): {name}? = {name}Reader.decode(bytes)?.toOwned()"));
    write_validate(out, m);
    line(out, 1, "}");
    let _ = writeln!(out, "}}\n");
    write_base_writer(out, m, set);
    write_validators(out, m, set);
}

//! TypeScript backend: consumes a SchemaSet (same source as the JSON IR) and emits `schema.ts`.
//!
//! Everything is generated with literal offsets so the runtime needs no schema: per message a
//! zero-copy Reader class, a base writer (used whenever the struct is inlined), validators per
//! version block, and a namespace with decode / fromReader / fromBytes / validate / encode.

use message_core::{element_size, FieldDescriptor, MessageDescriptor, SchemaSet, SimpleType, Type};
use std::fmt::Write as _;

pub fn generate_ts(set: &SchemaSet) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "// Generated by message-rs codegen; do not edit. Source of truth: the Rust #[derive(Message)] definitions."
    );
    let _ = writeln!(
        out,
        "// Two-layer API: XxxReader = lazy zero-copy view; Xxx = plain TS object (the namespace\n// provides decode/fromReader/fromBytes/validate/encode). Map keys are strings on the TS side."
    );
    let _ = writeln!(
        out,
        "import {{\n  readBool, readF32, readF64, readI16, readI32, readI64, readI8, readU16,\n  readU32, readU64, readU64Big, readU8, readBitmapBit, readSlot, utf8, slotBytes,\n  findExtBlock, findExtBlockIn, ScalarListView, StringListView, BytesListView, SlotListView,\n  StructListView, StructEvoListView, Writer, enumNum, utf8Encode, vStr, vSlot, vRegion,\n  vRegionShape, vExtent, vInstance, vEnum, ValidationError, type ValidationPath, type MessageCodec,\n  INSTANCE_HV, SHAPE_BIT, LEN_MASK,\n}} from './runtime';\n"
    );

    for e in &set.enums {
        let _ = writeln!(out, "export enum {} {{", e.name);
        for v in &e.variants {
            let _ = writeln!(out, "  {} = {},", v.name, v.value);
        }
        let _ = writeln!(out, "}}\n");
    }

    for m in &set.messages {
        write_message(&mut out, m, set);
    }

    // key dispatch table
    let _ = writeln!(out, "export function decodeBy(buf: Uint8Array) {{");
    let _ = writeln!(out, "  if (buf.length < 8) return null;");
    let _ = writeln!(out, "  const dv = new DataView(buf.buffer, buf.byteOffset, buf.byteLength);");
    let _ = writeln!(out, "  const key = dv.getUint32(0, true);");
    let _ = writeln!(out, "  switch (key) {{");
    for m in &set.messages {
        let _ = writeln!(out, "    case {}: return {}Reader.decode(buf);", m.key, m.name);
    }
    let _ = writeln!(out, "    default: return null;");
    let _ = writeln!(out, "  }}");
    let _ = writeln!(out, "}}");
    out
}

fn line(out: &mut String, level: usize, s: &str) {
    let _ = writeln!(out, "{}{s}", "  ".repeat(level));
}

/// Whether struct `name` has extension blocks: containers of it are then written in instance
/// mode (per-element / per-value slots, shape bit set).
fn has_ext(set: &SchemaSet, name: &str) -> bool {
    set.message(name).is_some_and(|m| !m.layout.ext_blocks.is_empty())
}

fn fixed_len_of(set: &SchemaSet, name: &str) -> usize {
    set.message(name).map(|m| m.layout.fixed_len).expect("planned struct")
}

fn camel(s: &str) -> String {
    let mut out = String::new();
    let mut upper = false;
    for c in s.chars() {
        if c == '_' {
            upper = true;
        } else if upper {
            out.extend(c.to_uppercase());
            upper = false;
        } else {
            out.push(c);
        }
    }
    out
}

fn pascal(s: &str) -> String {
    let c = camel(s);
    let mut out = String::new();
    let mut chars = c.chars();
    if let Some(f) = chars.next() {
        out.extend(f.to_uppercase());
        out.push_str(chars.as_str());
    }
    out
}

fn scalar_read_fn(ty: &str) -> &'static str {
    match ty {
        "bool" => "readBool",
        "u8" => "readU8",
        "i8" => "readI8",
        "u16" => "readU16",
        "i16" => "readI16",
        "u32" => "readU32",
        "i32" => "readI32",
        "u64" => "readU64",
        "i64" => "readI64",
        "f32" => "readF32",
        "f64" => "readF64",
        _ => "readU8",
    }
}

/// TS type name for a simple type.
fn simple_ts(ty: &str, precise: bool) -> String {
    match ty {
        "bool" => "boolean".into(),
        "u64" if precise => "bigint".into(),
        "u64" | "i64" | "u8" | "i8" | "u16" | "i16" | "u32" | "i32" | "f32" | "f64" => "number".into(),
        "string" => "string".into(),
        "bytes" => "Uint8Array".into(),
        _ => "number".into(),
    }
}

fn type_str(ty: &Type) -> Option<String> {
    match ty {
        Type::Simple(s) => Some(format!("{s:?}").to_lowercase()),
        _ => None,
    }
}

/// `Writer` method for a scalar.
fn writer_method(s: SimpleType) -> &'static str {
    match s {
        SimpleType::Bool => "bool",
        SimpleType::U8 => "u8",
        SimpleType::I8 => "i8",
        SimpleType::U16 => "u16",
        SimpleType::I16 => "i16",
        SimpleType::U32 => "u32",
        SimpleType::I32 => "i32",
        SimpleType::U64 => "u64",
        SimpleType::I64 => "i64",
        SimpleType::F32 => "f32",
        SimpleType::F64 => "f64",
        SimpleType::String | SimpleType::Bytes => unreachable!("slot-shaped types are not scalars"),
    }
}

// ---------- Reader ----------

/// (TS type, read expression) of a field.
fn field_read(f: &FieldDescriptor, origin: &str, set: &SchemaSet) -> (String, String) {
    let pos = format!("{origin} + {}", f.offset);
    match &f.ty {
        Type::Simple(_s) => {
            let t = type_str(&f.ty).unwrap();
            match t.as_str() {
                "string" => (
                    "string".into(),
                    format!(
                        "{{ const [o, l] = readSlot(this.dv, {pos}); return utf8(this.dv, o, l); }}"
                    ),
                ),
                "bytes" => (
                    "Uint8Array".into(),
                    format!("{{ const [o, l] = readSlot(this.dv, {pos}); return slotBytes(this.dv, o, l); }}"),
                ),
                "u64" if f.precise => (
                    "bigint".into(),
                    format!("return readU64Big(this.dv, {pos});"),
                ),
                _ => (
                    simple_ts(&t, false),
                    format!("return {}(this.dv, {pos});", scalar_read_fn(&t)),
                ),
            }
        }
        Type::Enum { name } => (
            name.clone(),
            format!("return readI32(this.dv, {pos}) as {name};"),
        ),
        Type::Struct { name } => (
            format!("{name}Reader"),
            format!(
                "{{ const [o, l] = readSlot(this.dv, {pos}); return new {name}Reader(this.dv, o, o + l, INSTANCE_HV); }}"
            ),
        ),
        Type::Array { body } => {
            let (vt, ctor) = elem_view(&body.elem, set);
            match body.fixed {
                Some(n) if !body.elem.is_slot_shaped() => (
                    vt,
                    format!("{{ {} }}", ctor.replace("OFF", &pos).replace("CNT", &n.to_string())),
                ),
                _ => (
                    vt,
                    format!(
                        "{{ const [o, l] = readSlot(this.dv, {pos}); {} }}",
                        ctor.replace("OFF", "o").replace("CNT", "l")
                    ),
                ),
            }
        }
        Type::Map { .. } => {
            let view = format!("{}MapView", pascal(&f.name));
            let body = format!(
                "{{ const [o, l] = readSlot(this.dv, {pos}); return new {view}(this.dv, o, l); }}"
            );
            (view, body)
        }
    }
}

/// Array element view: `OFF`/`CNT` are placeholders for the data-region start and element count.
fn elem_view(elem: &Type, set: &SchemaSet) -> (String, String) {
    match elem {
        Type::Simple(s) => {
            let t = format!("{s:?}").to_lowercase();
            if t == "string" {
                ("StringListView".into(), "return new StringListView(this.dv, OFF, CNT);".into())
            } else if t == "bytes" {
                ("BytesListView".into(), "return new BytesListView(this.dv, OFF, CNT);".into())
            } else {
                let rf = scalar_read_fn(&t);
                let ts = if t == "bool" { "boolean" } else { "number" };
                let w = s.fixed_size();
                (
                    format!("ScalarListView<{ts}>"),
                    format!("return new ScalarListView<{ts}>(this.dv, OFF, CNT, {w}, {rf});"),
                )
            }
        }
        Type::Enum { name } => (
            format!("StructListView<{name}>"),
            format!(
                "return new StructListView<{name}>(this.dv, OFF, CNT, 4, (dv, off) => readI32(dv, off) as {name});"
            ),
        ),
        Type::Struct { name } => {
            let stride = fixed_len_of(set, name);
            (
                format!("StructEvoListView<{name}Reader>"),
                format!(
                    "return new StructEvoListView<{name}Reader>(this.dv, OFF, CNT, {stride}, (dv, o, e, hv) => new {name}Reader(dv, o, e, hv));"
                ),
            )
        }
        Type::Array { .. } => (
            "SlotListView".into(),
            "return new SlotListView(this.dv, OFF, CNT);".into(),
        ),
        Type::Map { .. } => ("never".into(), String::new()),
    }
}

fn write_message(out: &mut String, m: &MessageDescriptor, set: &SchemaSet) {
    let name = &m.name;
    let ext_versions: Vec<u16> = m
        .layout
        .ext_blocks
        .iter()
        .map(|b| b.version)
        .collect();
    let ext_arr = format!(
        "[{}]",
        ext_versions.iter().map(|v| v.to_string()).collect::<Vec<_>>().join(", ")
    );
    let ext_fixed = format!(
        "{{ {} }}",
        m.layout.ext_blocks
            .iter()
            .map(|b| format!("{}: {}", b.version, b.fixed_len))
            .collect::<Vec<_>>()
            .join(", ")
    );

    let _ = writeln!(out, "export class {name}Reader {{");
    let _ = writeln!(out, "  static readonly KEY = {};", m.key);
    let _ = writeln!(out, "  static readonly FIXED_LEN = {};", m.layout.fixed_len);
    let _ = writeln!(out, "  static readonly EXT_VERSIONS: readonly number[] = {ext_arr};");
    let _ = writeln!(out, "  static readonly EXT_FIXED: Readonly<Record<number, number>> = {ext_fixed};");
    let _ = writeln!(
        out,
        "\n  /** `[origin, end)` is the extent this view may read (the payload for top-level messages and\n   *  open elements, the instance for self-contained structs); `hv` is the writer's header version\n   *  (INSTANCE_HV inside instances). */\n  constructor(private readonly dv: DataView, private readonly origin: number, private readonly end: number, private readonly hv: number) {{}}\n"
    );
    let _ = writeln!(
        out,
        "  static decode(buf: Uint8Array): {name}Reader | null {{
    if (buf.length < 8 + {fixed}) return null;
    const full = new DataView(buf.buffer, buf.byteOffset, buf.byteLength);
    if (full.getUint32(0, true) !== {name}Reader.KEY) return null;
    const payload = new DataView(buf.buffer, buf.byteOffset + 8, buf.byteLength - 8);
    return new {name}Reader(payload, 0, payload.byteLength, full.getUint8(6));
  }}\n",
        fixed = m.layout.fixed_len,
    );

    for f in &m.fields {
        if f.reserved {
            continue;
        }
        let origin = if f.since > 1 { "__origin" } else { "this.origin" };
        let (ret, body) = field_read(f, origin, set);
        let ts_name = camel(&f.name);
        if f.since > 1 {
            let since = f.since;
            let find = format!(
                "findExtBlockIn(this.dv, {name}Reader.EXT_VERSIONS, this.hv, {since}, {name}Reader.EXT_FIXED[{since}], this.origin, this.end)"
            );
            if f.optional {
                let _ = writeln!(
                    out,
                    "  get {ts_name}(): {ret} | null {{
    const bs = {find};
    if (bs === null || !readBitmapBit(this.dv, bs, {bit})) return null;
    {{
      const __origin = bs;
      {body}
    }}
  }}",
                    bit = f.optional_bit.unwrap_or(0)
                );
            } else {
                let _ = writeln!(
                    out,
                    "  get {ts_name}(): {ret} {{
    const bs = {find};
    if (bs === null) {{ {} }}
    {{
      const __origin = bs;
      {body}
    }}
  }}",
                    default_ts(f, set)
                );
            }
        } else if f.optional {
            let _ = writeln!(
                out,
                "  get {ts_name}(): {ret} | null {{
    if (!readBitmapBit(this.dv, this.origin, {})) return null;
    {body}
  }}",
                f.optional_bit.unwrap_or(0),
            );
        } else {
            let _ = writeln!(out, "  get {ts_name}(): {ret} {{\n    {body}\n  }}");
        }
    }

    // toUser(): Reader -> plain object (mirrors Rust's to_owned)
    let mut to_user_fields = String::new();
    for f in &m.fields {
        if f.reserved {
            continue;
        }
        let c = camel(&f.name);
        let _ = writeln!(
            to_user_fields,
            "      {}: {},",
            c,
            materialize_field_expr(f, set, &c)
        );
    }
    let _ = writeln!(
        out,
        "\n  toUser(): {name} {{\n    return {{\n{}    }};\n  }}",
        to_user_fields
    );
    let _ = writeln!(out, "}}\n");

    write_base_writer(out, m, set);
    write_validators(out, m, set);

    // Plain-object interface + namespace
    let mut iface_fields = String::new();
    for f in &m.fields {
        if f.reserved {
            continue;
        }
        let c = camel(&f.name);
        let t = ts_field_type(f, set);
        let _ = writeln!(iface_fields, "  {}: {};", c, t);
    }
    let _ = writeln!(out, "export interface {name} {{\n{}}}\n", iface_fields);
    let _ = writeln!(out, "export namespace {name} {{");
    let _ = writeln!(out, "  export const codec: MessageCodec<{name}> = {{ key: {key}, encode, fromBytes }};", key = m.key);
    let _ = writeln!(
        out,
        "  export function decode(buf: Uint8Array): {name}Reader | null {{
    return {name}Reader.decode(buf);
  }}
  export function fromReader(r: {name}Reader): {name} {{
    return r.toUser();
  }}
  export function fromBytes(buf: Uint8Array): {name} | null {{
    const r = {name}Reader.decode(buf);
    return r === null ? null : r.toUser();
  }}"
    );
    write_validate(out, m);
    write_encode(out, m, set);
    let _ = writeln!(out, "}}\n");

    // map views
    for f in &m.fields {
        if f.reserved {
            continue;
        }
        if let Type::Map { body } = &f.ty {
            let view = format!("{}MapView", pascal(&f.name));
            let l = message_core::map_entry_layouts(&body.key, &body.value, set).expect("planned map");
            let (k_ret, k_body) = map_part_read(&body.key, "", set);
            let (v_ret, v_body) = map_part_read(&body.value, "", set);
            // Struct values: the writer's shape bit selects open entries (value = fixed region)
            // or instance entries (value = slot to a self-contained instance).
            let (stride, v_off, v_body) = match body.value.as_ref() {
                Type::Struct { name } => (
                    format!("(this.inst ? {} : {})", l.inst_stride, l.open_stride),
                    format!("(this.inst ? {} : {})", l.inst_value_offset, l.open_value_offset),
                    format!(
                        "if (this.inst) {{ const [o, l] = readSlot(this.dv, e); return new {name}Reader(this.dv, o, o + l, INSTANCE_HV); }}\n    return new {name}Reader(this.dv, e, this.dv.byteLength, 0);"
                    ),
                ),
                _ => (l.open_stride.to_string(), l.open_value_offset.to_string(), v_body),
            };
            let _ = writeln!(
                out,
                "export class {view} {{
  constructor(private readonly dv: DataView, private readonly start: number, private readonly rawLen: number) {{}}
  get length(): number {{ return this.rawLen & LEN_MASK; }}
  private get inst(): boolean {{ return this.rawLen >= SHAPE_BIT; }}
  key(i: number): {k_ret} {{
    const e = this.start + i * {stride};
    {k_body}
  }}
  value(i: number): {v_ret} {{
    const e = this.start + i * {stride} + {v_off};
    {v_body}
  }}
  entry(i: number): [{k_ret}, {v_ret}] {{ return [this.key(i), this.value(i)]; }}
}}

"
            );
        }
    }
}

fn map_part_read(ty: &Type, off_suffix: &str, set: &SchemaSet) -> (String, String) {
    match ty {
        Type::Simple(s) => {
            let t = format!("{s:?}").to_lowercase();
            if t == "string" {
                (
                    "string".into(),
                    format!("const [o, l] = readSlot(this.dv, e); return utf8(this.dv, o, l);"),
                )
            } else {
                (simple_ts(&t, false), format!("return {}(this.dv, e{off_suffix});", scalar_read_fn(&t)))
            }
        }
        Type::Enum { name } => (
            name.clone(),
            format!("return readI32(this.dv, e{off_suffix}) as {name};"),
        ),
        Type::Struct { name } => (
            format!("{name}Reader"),
            format!("return new {name}Reader(this.dv, e{off_suffix}, this.dv.byteLength, 0);"),
        ),
        Type::Array { body } => {
            let (vt, ctor) = elem_view(&body.elem, set);
            (
                vt,
                format!(
                    "const [o, l] = readSlot(this.dv, e{off_suffix}); {}",
                    ctor.replace("OFF", "o").replace("CNT", "l")
                ),
            )
        }
        _ => ("never".into(), "throw new Error('unsupported');".into()),
    }
}

fn default_ts(f: &FieldDescriptor, set: &SchemaSet) -> String {
    match &f.ty {
        Type::Simple(s) => {
            let t = format!("{s:?}").to_lowercase();
            match t.as_str() {
                "string" => "return '';".into(),
                "bytes" => "return new Uint8Array(0);".into(),
                "bool" => "return false;".into(),
                "u64" if f.precise => "return 0n;".into(),
                _ => "return 0;".into(),
            }
        }
        Type::Enum { name } => format!("return 0 as {name};"),
        Type::Struct { .. } => format!(
            "throw new Error('field `{}` missing: data written by an older schema version');",
            f.name
        ),
        Type::Array { body } => {
            let (_vt, ctor) = elem_view(&body.elem, set);
            ctor.replace("OFF", "0").replace("CNT", "0")
        }
        Type::Map { .. } => format!("return new {}MapView(this.dv, 0, 0);", pascal(&f.name)),
    }
}

/// Inner view construction for struct elements of nested arrays (from slot values o/l).
fn struct_evo_ctor(name: &str, set: &SchemaSet, dv: &str, o: &str, l: &str) -> String {
    format!(
        "new StructEvoListView<{name}Reader>({dv}, {o}, {l}, {}, (dv2, o2, e2, hv2) => new {name}Reader(dv2, o2, e2, hv2))",
        fixed_len_of(set, name)
    )
}

// ---------- Plain-object layer (interface types + materialization) ----------

fn ts_type_of(ty: &Type, precise: bool, set: &SchemaSet) -> String {
    match ty {
        Type::Simple(s) => {
            let t = format!("{s:?}").to_lowercase();
            match t.as_str() {
                "bool" => "boolean".into(),
                "string" => "string".into(),
                "bytes" => "Uint8Array".into(),
                "u64" if precise => "bigint".into(),
                _ => "number".into(),
            }
        }
        Type::Enum { name } => name.clone(),
        Type::Struct { name } => name.clone(),
        Type::Array { body } => format!("{}[]", ts_type_of(&body.elem, false, set)),
        Type::Map { body } => format!("Record<string, {}>", ts_type_of(&body.value, false, set)),
    }
}

fn ts_field_type(f: &FieldDescriptor, set: &SchemaSet) -> String {
    let base = ts_type_of(&f.ty, f.precise, set);
    if f.optional {
        format!("{base} | null")
    } else {
        base
    }
}

/// Materialization expression turning the `this.xxx` getter into a plain field value.
fn materialize_field_expr(f: &FieldDescriptor, set: &SchemaSet, c: &str) -> String {
    let base = match &f.ty {
        Type::Simple(s) => {
            let t = format!("{s:?}").to_lowercase();
            if t == "bytes" {
                format!("new Uint8Array(this.{c})")
            } else {
                format!("this.{c}")
            }
        }
        Type::Enum { .. } => format!("this.{c}"),
        Type::Struct { name } => format!("{name}.fromReader(this.{c})"),
        Type::Array { body } => materialize_list(&format!("this.{c}"), &body.elem, set),
        Type::Map { body } => {
            let v_expr = match body.value.as_ref() {
                Type::Simple(s) => {
                    let t = format!("{s:?}").to_lowercase();
                    if t == "bytes" {
                        format!("new Uint8Array(this.{c}.value(i))")
                    } else {
                        format!("this.{c}.value(i)")
                    }
                }
                Type::Struct { name } => {
                    format!("{name}.fromReader(this.{c}.value(i))")
                }
                Type::Array { body } => format!(
                    "(() => {{ const mv = this.{c}.value(i); return {}; }})()",
                    materialize_list("mv", &body.elem, set)
                ),
                _ => format!("this.{c}.value(i)"),
            };
            format!(
                "(() => {{ const o: Record<string, {}> = {{}}; for (let i = 0; i < this.{c}.length; i++) o[this.{c}.key(i)] = {v_expr}; return o; }})()",
                ts_type_of(&body.value, false, set)
            )
        }
    };
    if f.optional {
        format!("this.{c} === null ? null : {base}")
    } else {
        base
    }
}

/// List view -> array literal (nested arrays recurse through SlotListView).
fn materialize_list(view: &str, elem: &Type, set: &SchemaSet) -> String {
    match elem {
        Type::Simple(s) => {
            let t = format!("{s:?}").to_lowercase();
            if t == "bytes" {
                format!("Array.from({{ length: {view}.length }}, (_, i) => new Uint8Array({view}.get(i)))")
            } else {
                format!("Array.from({{ length: {view}.length }}, (_, i) => {view}.get(i))")
            }
        }
        Type::Enum { .. } => format!("Array.from({{ length: {view}.length }}, (_, i) => {view}.get(i))"),
        Type::Struct { name } => format!(
            "Array.from({{ length: {view}.length }}, (_, i) => {name}.fromReader({view}.get(i)))"
        ),
        Type::Array { body } => {
            // Nested dynamic array: elements are slots; build the inner view, then recurse
            let inner = materialize_list("iv", &body.elem, set);
            format!(
                "Array.from({{ length: {view}.length }}, (_, i) => {{ const [o, l] = {view}.slotOf(i); {} return {inner}; }})",
                nested_view_decl(&body.elem, set),
                inner = inner
            )
        }
        Type::Map { .. } => "[] as never[]".to_string(),
    }
}

/// Inner view declaration for nested array elements (`const iv = ...;`).
fn nested_view_decl(elem: &Type, set: &SchemaSet) -> String {
    format!("const iv = {};", nested_elem_ctor(elem, set))
}

/// Inner view construction expression (from slot values o/l).
fn nested_elem_ctor(elem: &Type, set: &SchemaSet) -> String {
    match elem {
        Type::Simple(s) => {
            let t = format!("{s:?}").to_lowercase();
            match t.as_str() {
                "string" => "new StringListView(this.dv, o, l)".to_string(),
                "bytes" => "new BytesListView(this.dv, o, l)".to_string(),
                _ => {
                    let rf = scalar_read_fn(&t);
                    let w = s.fixed_size();
                    let ts = if t == "bool" { "boolean" } else { "number" };
                    format!("new ScalarListView<{ts}>(this.dv, o, l, {w}, {rf})")
                }
            }
        }
        Type::Enum { name } => format!(
            "new StructListView<{name}>(this.dv, o, l, 4, (dv2, off2) => readI32(dv2, off2) as {name})"
        ),
        Type::Struct { name } => struct_evo_ctor(name, set, "this.dv", "o", "l"),
        Type::Array { .. } => "new SlotListView(this.dv, o, l)".to_string(),
        Type::Map { .. } => "null as never".to_string(),
    }
}

// ---------- Writer ----------

/// `function __writeXxxBase(w, base, value)`: the base fields of a struct at an already
/// reserved position (used for inline fields, struct array elements and map values).
fn write_base_writer(out: &mut String, m: &MessageDescriptor, set: &SchemaSet) {
    let _ = writeln!(
        out,
        "function __write{}Base(w: Writer, base: number, value: {}): void {{",
        m.name, m.name
    );
    for f in m.fields.iter().filter(|f| f.since == 1) {
        write_field(out, 1, f, &format!("value.{}", camel(&f.name)), "base", set);
    }
    let _ = writeln!(out, "}}\n");
    if !m.layout.ext_blocks.is_empty() {
        // the extension chain, appended after the base var data (top-level message or instance)
        let _ = writeln!(out, "function __write{}Ext(w: Writer, value: {}): void {{", m.name, m.name);
        for b in &m.layout.ext_blocks {
            line(out, 1, "{");
            line(out, 2, &format!("const blk = w.reserve({});", b.fixed_len));
            for f in m.fields.iter().filter(|f| f.since == b.version) {
                write_field(out, 2, f, &format!("value.{}", camel(&f.name)), "blk", set);
            }
            line(out, 2, &format!("w.trailer(blk, {});", b.version));
            line(out, 1, "}");
        }
        let _ = writeln!(out, "}}\n");
    }
    // self-contained instance: fixed region, own var data, extension chain; returns its start
    let _ = writeln!(out, "function __write{}Instance(w: Writer, value: {}): number {{", m.name, m.name);
    line(out, 1, &format!("const s = w.reserve({});", m.layout.fixed_len));
    line(out, 1, &format!("__write{}Base(w, s, value);", m.name));
    if !m.layout.ext_blocks.is_empty() {
        line(out, 1, &format!("__write{}Ext(w, value);", m.name));
    }
    line(out, 1, "return s;");
    let _ = writeln!(out, "}}\n");
}

/// `export function encode(value)`: header + base + extension blocks, all with literal offsets.
fn write_encode(out: &mut String, m: &MessageDescriptor, _set: &SchemaSet) {
    let need = 8 + m.layout.fixed_len;
    let max_version = m.layout.ext_blocks.last().map_or(0, |b| b.version);
    line(out, 2, "/** Canonical encoding (byte-identical to Rust): declaration-order var data, sorted map keys. */");
    line(out, 2, &format!("export function encode(value: {}): Uint8Array {{", m.name));
    line(out, 3, &format!("const w = new Writer({need});"));
    line(out, 3, "w.reserve(8);");
    line(out, 3, &format!("const base = w.reserve({});", m.layout.fixed_len));
    line(out, 3, &format!("__write{}Base(w, base, value);", m.name));
    if !m.layout.ext_blocks.is_empty() {
        line(out, 3, &format!("__write{}Ext(w, value);", m.name));
    }
    line(out, 3, &format!("w.u32(0, {});", m.key));
    line(out, 3, &format!("w.u16(4, {});", m.layout.fixed_len));
    line(out, 3, &format!("w.u8(6, {max_version});"));
    line(out, 3, "w.u8(7, 0);");
    line(out, 3, "return w.finish();");
    line(out, 2, "}\n");
}

/// Write one field of a block: optional fields set their bitmap bit, reserved fields are left
/// zeroed, everything else goes through `write_value` / `write_map_field`.
fn write_field(out: &mut String, level: usize, f: &FieldDescriptor, val: &str, block: &str, set: &SchemaSet) {
    if f.reserved {
        return;
    }
    let pos = format!("{block} + {}", f.offset);
    if f.optional {
        line(out, level, "{");
        line(out, level + 1, &format!("const v = {val};"));
        line(out, level + 1, "if (v !== null && v !== undefined) {");
        line(out, level + 2, &format!("w.bit({block}, {});", f.optional_bit.unwrap_or(0)));
        write_value_or_map(out, level + 2, f, &f.ty.clone(), "v", &pos, set);
        line(out, level + 1, "}");
        line(out, level, "}");
    } else {
        write_value_or_map(out, level, f, &f.ty.clone(), val, &pos, set);
    }
}

fn write_value_or_map(out: &mut String, level: usize, f: &FieldDescriptor, ty: &Type, val: &str, pos: &str, set: &SchemaSet) {
    match ty {
        Type::Map { .. } => write_map_field(out, level, f, val, pos, set),
        _ => write_value(out, level, ty, val, pos, set, 0),
    }
}

/// Statements writing `val` of type `ty` at absolute position `pos`. `depth` keeps loop
/// variables unique; it is only ever 0 for fields (maps cannot nest).
fn write_value(out: &mut String, level: usize, ty: &Type, val: &str, pos: &str, set: &SchemaSet, depth: usize) {
    match ty {
        Type::Simple(SimpleType::String) => {
            line(out, level, &format!("{{ const b = utf8Encode({val}); w.slot({pos}, w.append(b), b.length); }}"));
        }
        Type::Simple(SimpleType::Bytes) => {
            line(out, level, &format!("w.slot({pos}, w.append({val}), {val}.length);"));
        }
        Type::Simple(s) => {
            line(out, level, &format!("w.{}({pos}, {val});", writer_method(*s)));
        }
        Type::Enum { name } => {
            line(out, level, &format!("w.i32({pos}, enumNum({name}, {val}));"));
        }
        Type::Struct { name } => {
            line(out, level, &format!("{{ const s = __write{name}Instance(w, {val}); w.slot({pos}, w.rel(s), w.length - s); }}"));
        }
        Type::Array { body } if matches!(body.elem.as_ref(), Type::Struct { name } if has_ext(set, name)) => {
            // elements with extension fields: per-element instance slots, shape bit set
            let Type::Struct { name } = body.elem.as_ref() else { unreachable!() };
            let (a, i, r) = (format!("a{depth}"), format!("i{depth}"), format!("r{depth}"));
            let elem_ty = ts_type_of(ty, false, set);
            line(out, level, "{");
            line(out, level + 1, &format!("const {a}: {elem_ty} = {val} ?? [];"));
            line(out, level + 1, &format!("const {r} = w.reserve({a}.length * 8);"));
            line(out, level + 1, &format!("for (let {i} = 0; {i} < {a}.length; {i}++) {{"));
            line(out, level + 2, &format!("const s = __write{name}Instance(w, {a}[{i}]);"));
            line(out, level + 2, &format!("w.slot({r} + {i} * 8, w.rel(s), w.length - s);"));
            line(out, level + 1, "}");
            line(out, level + 1, &format!("w.slot({pos}, w.rel({r}), ({a}.length | SHAPE_BIT) >>> 0);"));
            line(out, level, "}");
        }
        Type::Array { body } => {
            let w = element_size(&body.elem, set).expect("element size of a planned schema");
            let (a, i, r) = (format!("a{depth}"), format!("i{depth}"), format!("r{depth}"));
            let elem_ty = ts_type_of(ty, false, set);
            if body.fixed.is_some() && !body.elem.is_slot_shaped() {
                line(out, level, "{");
                line(out, level + 1, &format!("const {a}: {elem_ty} = {val} ?? [];"));
                line(out, level + 1, &format!("for (let {i} = 0; {i} < {}; {i}++) {{", body.fixed.unwrap()));
                write_open_elem(out, level + 2, &body.elem, &format!("{a}[{i}]"), &format!("{pos} + {i} * {w}"), set, depth + 1);
                line(out, level + 1, "}");
                line(out, level, "}");
            } else {
                line(out, level, "{");
                line(out, level + 1, &format!("const {a}: {elem_ty} = {val} ?? [];"));
                line(out, level + 1, &format!("const {r} = w.reserve({a}.length * {w});"));
                line(out, level + 1, &format!("for (let {i} = 0; {i} < {a}.length; {i}++) {{"));
                write_open_elem(out, level + 2, &body.elem, &format!("{a}[{i}]"), &format!("{r} + {i} * {w}"), set, depth + 1);
                line(out, level + 1, "}");
                line(out, level + 1, &format!("w.slot({pos}, w.rel({r}), {a}.length);"));
                line(out, level, "}");
            }
        }
        Type::Map { .. } => unreachable!("maps are written by write_map_field"),
    }
}

/// Map slot length expression: the entry count, with the shape bit when the values are instances.
fn shape_len(count: &str, value: &Type, set: &SchemaSet) -> String {
    match value {
        Type::Struct { name } if has_ext(set, name) => format!("({count} | SHAPE_BIT) >>> 0"),
        _ => count.to_string(),
    }
}

/// An element of a shape=0 (open) array: struct elements are written as their fixed-region
/// footprint at `pos` (their var data appended), everything else as a regular value.
fn write_open_elem(out: &mut String, level: usize, ty: &Type, val: &str, pos: &str, set: &SchemaSet, depth: usize) {
    match ty {
        Type::Struct { name } => line(out, level, &format!("__write{name}Base(w, {pos}, {val});")),
        _ => write_value(out, level, ty, val, pos, set, depth),
    }
}

/// A map value at `pos` inside its entry: struct values with extension fields are instance slots,
/// unevolved struct values are inlined fixed regions.
fn write_map_value(out: &mut String, level: usize, ty: &Type, val: &str, pos: &str, set: &SchemaSet) {
    match ty {
        Type::Struct { name } if has_ext(set, name) => write_value(out, level, ty, val, pos, set, 0),
        _ => write_open_elem(out, level, ty, val, pos, set, 0),
    }
}

/// A map field: entries sorted by the key's wire value (what makes the encoding canonical).
fn write_map_field(out: &mut String, level: usize, f: &FieldDescriptor, val: &str, pos: &str, set: &SchemaSet) {
    let Type::Map { body } = &f.ty else { unreachable!("write_map_field on a non-map") };
    let stride = f.element_size.expect("planned stride");
    let v_off = f.map_value_offset.expect("planned value offset");
    let val_ty = ts_type_of(&body.value, false, set);
    line(out, level, "{");
    line(out, level + 1, &format!("const o: Record<string, {val_ty}> = {val} ?? {{}};"));
    if let Type::Simple(SimpleType::String) = body.key.as_ref() {
        line(out, level + 1, "const ks = Object.keys(o).sort();");
        line(out, level + 1, &format!("const r = w.reserve(ks.length * {stride});"));
        line(out, level + 1, "for (let i = 0; i < ks.length; i++) {");
        line(out, level + 2, &format!("const e = r + i * {stride};"));
        line(out, level + 2, "const k = ks[i];");
        line(out, level + 2, "{ const b = utf8Encode(k); w.slot(e, w.append(b), b.length); }");
        write_map_value(out, level + 2, &body.value, "o[k]", &format!("e + {v_off}"), set);
        line(out, level + 1, "}");
        line(out, level + 1, &format!("w.slot({pos}, w.rel(r), {});", shape_len("ks.length", &body.value, set)));
    } else {
        // bool / scalar / enum keys: the object key is a string; resolve it to its wire value
        // (or BigInt for 64-bit keys), sort by that, and look the value up by the original key.
        let (conv, tuple, cmp, kw): (String, &str, &str, String) = match body.key.as_ref() {
            Type::Simple(SimpleType::Bool) => (
                "k === 'true' ? 1 : 0".into(),
                "number",
                "a[0] - b[0]",
                "w.u8(e, es[i][0]);".into(),
            ),
            Type::Simple(s @ (SimpleType::U64 | SimpleType::I64)) => (
                "BigInt(k)".into(),
                "bigint",
                "(a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0)",
                format!("w.{}(e, es[i][0]);", writer_method(*s)),
            ),
            Type::Enum { name } => (
                format!("Number.isNaN(Number(k)) ? enumNum({name}, k) : Number(k)"),
                "number",
                "a[0] - b[0]",
                "w.i32(e, es[i][0]);".into(),
            ),
            Type::Simple(s) => (
                "Number(k)".into(),
                "number",
                "a[0] - b[0]",
                format!("w.{}(e, es[i][0]);", writer_method(*s)),
            ),
            _ => unreachable!("invalid map key rejected by the planner"),
        };
        line(out, level + 1, &format!("const es = Object.keys(o).map((k) => [{conv}, k] as [{tuple}, string]);"));
        line(out, level + 1, &format!("es.sort((a, b) => {cmp});"));
        line(out, level + 1, &format!("const r = w.reserve(es.length * {stride});"));
        line(out, level + 1, "for (let i = 0; i < es.length; i++) {");
        line(out, level + 2, &format!("const e = r + i * {stride};"));
        line(out, level + 2, "const k = es[i][1];");
        line(out, level + 2, &kw);
        write_map_value(out, level + 2, &body.value, "o[k]", &format!("e + {v_off}"), set);
        line(out, level + 1, "}");
        line(out, level + 1, &format!("w.slot({pos}, w.rel(r), {});", shape_len("es.length", &body.value, set)));
    }
    line(out, level, "}");
}

// ---------- Validator ----------

/// `function __validateXxxBase(dv, base, hv, path)` plus one `__validateXxxV{n}` per extension
/// block. Leaf errors carry no field; the helpers append `field` (and the element index).
fn write_validators(out: &mut String, m: &MessageDescriptor, set: &SchemaSet) {
    let _ = writeln!(
        out,
        "function __validate{}Base(dv: DataView, base: number, hv: number, path: ValidationPath): void {{",
        m.name
    );
    for f in m.fields.iter().filter(|f| f.since == 1) {
        validate_field(out, 1, f, "base", set);
    }
    let _ = writeln!(out, "}}");
    for b in &m.layout.ext_blocks {
        let _ = writeln!(
            out,
            "function __validate{}V{}(dv: DataView, base: number, hv: number, path: ValidationPath): void {{",
            m.name, b.version
        );
        for f in m.fields.iter().filter(|f| f.since == b.version) {
            validate_field(out, 1, f, "base", set);
        }
        let _ = writeln!(out, "}}");
    }
    // self-contained instance in [lo, hi): base, then every extension block the chain offers
    // (no version is promised inside an instance, so absent blocks are legal)
    let _ = writeln!(
        out,
        "function __validate{}Inst(dv: DataView, lo: number, hi: number, path: ValidationPath): void {{",
        m.name
    );
    line(out, 1, &format!("__validate{}Base(dv, lo, INSTANCE_HV, path);", m.name));
    for b in m.layout.ext_blocks.iter().rev() {
        let v = b.version;
        line(out, 1, "{");
        line(out, 2, &format!(
            "const bs = findExtBlockIn(dv, {name}Reader.EXT_VERSIONS, INSTANCE_HV, {v}, {fixed}, lo, hi);",
            name = m.name,
            fixed = b.fixed_len
        ));
        line(out, 2, &format!("if (bs !== null) __validate{}V{v}(dv, bs, INSTANCE_HV, path);", m.name));
        line(out, 1, "}");
    }
    if m.layout.ext_blocks.is_empty() {
        line(out, 1, "void hi;");
    }
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);
}

/// `export function validate(buf)`: header, base, then every extension block the header
/// promises (highest version first, so a corrupt tail is reported at the block that owns it).
fn write_validate(out: &mut String, m: &MessageDescriptor) {
    let need = 8 + m.layout.fixed_len;
    line(out, 2, "/** Strictly check an untrusted buffer; after null no getter can throw. */");
    line(out, 2, "export function validate(buf: Uint8Array): ValidationError | null {");
    line(out, 3, "try {");
    line(out, 3, &format!("  if (buf.length < {need}) throw new ValidationError(`buffer too short: need {need} bytes, got ${{buf.length}}`);"));
    line(out, 3, "  const full = new DataView(buf.buffer, buf.byteOffset, buf.byteLength);");
    line(out, 3, "  const key = full.getUint32(0, true);");
    line(out, 3, &format!("  if (key !== {}) throw new ValidationError(`key mismatch: expected {}, got ${{key}}`);", m.key, m.key));
    line(out, 3, "  const fl = full.getUint16(4, true);");
    line(out, 3, &format!("  if (fl !== {}) throw new ValidationError(`header fixed_len mismatch: expected {}, got ${{fl}}`);", m.layout.fixed_len, m.layout.fixed_len));
    line(out, 3, "  const hv = full.getUint8(6);");
    line(out, 3, "  const dv = new DataView(buf.buffer, buf.byteOffset + 8, buf.byteLength - 8);");
    line(out, 3, "  const path: ValidationPath = [];");
    line(out, 3, &format!("  __validate{}Base(dv, 0, hv, path);", m.name));
    for b in m.layout.ext_blocks.iter().rev() {
        let v = b.version;
        line(out, 3, &format!("  if (hv >= {v}) {{"));
        line(out, 4, &format!("const bs = findExtBlock(dv, {name}Reader.EXT_VERSIONS, hv, {v}, {fixed});", name = m.name, fixed = b.fixed_len));
        line(out, 4, &format!("if (bs === null) throw new ValidationError('extension block v{v} missing or malformed');"));
        line(out, 4, &format!("__validate{}V{v}(dv, bs, hv, path);", m.name));
        line(out, 3, "  }");
    }
    line(out, 3, "  return null;");
    line(out, 3, "} catch (e) {");
    line(out, 3, "  if (e instanceof ValidationError) return e;");
    line(out, 3, "  throw e;");
    line(out, 3, "}");
    line(out, 2, "}\n");
}

fn validate_field(out: &mut String, level: usize, f: &FieldDescriptor, block: &str, set: &SchemaSet) {
    if f.reserved {
        return;
    }
    let pos = format!("{block} + {}", f.offset);
    let field = camel(&f.name);
    if f.optional {
        line(out, level, &format!("if (readBitmapBit(dv, {block}, {})) {{", f.optional_bit.unwrap_or(0)));
        validate_value_or_map(out, level + 1, f, &f.ty.clone(), &pos, &field, None, set, 0);
        line(out, level, "}");
    } else {
        validate_value_or_map(out, level, f, &f.ty.clone(), &pos, &field, None, set, 0);
    }
}

fn validate_value_or_map(out: &mut String, level: usize, f: &FieldDescriptor, ty: &Type, pos: &str, field: &str, idx: Option<&str>, set: &SchemaSet, depth: usize) {
    match ty {
        Type::Map { .. } => validate_map_field(out, level, f, pos, field, set),
        _ => validate_value(out, level, ty, pos, field, idx, set, depth),
    }
}

/// `idx` is the loop variable when the value is an array element / map entry.
fn validate_value(out: &mut String, level: usize, ty: &Type, pos: &str, field: &str, idx: Option<&str>, set: &SchemaSet, depth: usize) {
    let suffix = idx.map(|i| format!(", {i}")).unwrap_or_default();
    match ty {
        Type::Simple(s) => match s {
            SimpleType::String => line(out, level, &format!("vStr(dv, {pos}, path, '{field}'{suffix});")),
            SimpleType::Bytes => line(out, level, &format!("vSlot(dv, {pos}, path, '{field}'{suffix});")),
            _ => {}
        },
        Type::Enum { name } => {
            line(out, level, &format!("vEnum({name}, '{name}', dv, {pos}, path, '{field}'{suffix});"));
        }
        Type::Struct { name } => {
            line(out, level, &format!(
                "{{ const [lo, hi] = vInstance(dv, {pos}, path, '{field}'{suffix}); __validate{name}Inst(dv, lo, hi, [...path, '{field}'{suffix}]); }}"
            ));
        }
        Type::Array { body } if matches!(body.elem.as_ref(), Type::Struct { .. }) => {
            // the writer's shape bit selects open footprints (fixed regions) vs instance slots
            let Type::Struct { name } = body.elem.as_ref() else { unreachable!() };
            let fixed = fixed_len_of(set, name);
            let (o, n, s, i) = (format!("o{depth}"), format!("n{depth}"), format!("s{depth}"), format!("i{depth}"));
            line(out, level, "{");
            line(out, level + 1, &format!("const [{o}, {n}, {s}] = vRegionShape(dv, {pos}, path, '{field}'{suffix});"));
            line(out, level + 1, &format!("if ({s}) {{"));
            line(out, level + 2, &format!("for (let {i} = 0; {i} < {n}; {i}++) {{"));
            line(out, level + 3, &format!(
                "const [lo, hi] = vInstance(dv, {o} + {i} * 8, path, '{field}', {i}); __validate{name}Inst(dv, lo, hi, [...path, '{field}', {i}]);"
            ));
            line(out, level + 2, "}");
            line(out, level + 1, "} else {");
            line(out, level + 2, &format!("vExtent(dv, {o}, {n}, {fixed}, path, '{field}'{suffix});"));
            line(out, level + 2, &format!(
                "for (let {i} = 0; {i} < {n}; {i}++) __validate{name}Base(dv, {o} + {i} * {fixed}, 0, [...path, '{field}', {i}]);"
            ));
            line(out, level + 1, "}");
            line(out, level, "}");
        }
        Type::Array { body } => {
            let w = element_size(&body.elem, set).expect("element size of a planned schema");
            if body.fixed.is_some() && !body.elem.is_slot_shaped() {
                // inline fixed-length array: only at field level, so the enclosing idx is None
                let n = body.fixed.unwrap();
                let i = format!("i{depth}");
                match body.elem.as_ref() {
                    Type::Simple(s) if s.is_scalar() => {}
                    Type::Enum { name } => {
                        line(out, level, &format!("for (let {i} = 0; {i} < {n}; {i}++) {{"));
                        line(out, level + 1, &format!("vEnum({name}, '{name}', dv, {pos} + {i} * {w}, path, '{field}', {i});"));
                        line(out, level, "}");
                    }
                    Type::Struct { name } => {
                        line(out, level, &format!(
                            "for (let {i} = 0; {i} < {n}; {i}++) __validate{name}Base(dv, {pos} + {i} * {w}, hv, [...path, '{field}', {i}]);"
                        ));
                    }
                    _ => unreachable!("inline fixed arrays only hold inline-shaped elements"),
                }
            } else if is_scalar(&body.elem) {
                line(out, level, &format!("vRegion(dv, {pos}, {w}, path, '{field}'{suffix});"));
            } else {
                let (o, n, i) = (format!("o{depth}"), format!("n{depth}"), format!("i{depth}"));
                line(out, level, "{");
                line(out, level + 1, &format!("const [{o}, {n}] = vRegion(dv, {pos}, {w}, path, '{field}'{suffix});"));
                line(out, level + 1, &format!("for (let {i} = 0; {i} < {n}; {i}++) {{"));
                validate_value(out, level + 2, &body.elem, &format!("{o} + {i} * {w}"), field, Some(&i), set, depth + 1);
                line(out, level + 1, "}");
                line(out, level, "}");
            }
        }
        Type::Map { .. } => unreachable!("maps are validated by validate_map_field"),
    }
}

fn is_scalar(t: &Type) -> bool {
    matches!(t, Type::Simple(s) if s.is_scalar())
}

/// A map field: the entry region, then every key and value with the entry index in the path.
fn validate_map_field(out: &mut String, level: usize, f: &FieldDescriptor, pos: &str, field: &str, set: &SchemaSet) {
    let Type::Map { body } = &f.ty else { unreachable!("validate_map_field on a non-map") };
    let stride = f.element_size.expect("planned stride");
    let v_off = f.map_value_offset.expect("planned value offset");
    if is_scalar(&body.key) && is_scalar(&body.value) {
        line(out, level, &format!("vRegion(dv, {pos}, {stride}, path, '{field}');"));
        return;
    }
    if let Type::Struct { name } = body.value.as_ref() {
        // the writer's shape bit selects the entry layout: open (value = fixed region) or
        // instance (value = slot to a self-contained instance)
        let l = message_core::map_entry_layouts(&body.key, &body.value, set).expect("planned map");
        line(out, level, "{");
        line(out, level + 1, &format!("const [o0, n0, s0] = vRegionShape(dv, {pos}, path, '{field}');"));
        line(out, level + 1, &format!("const st = s0 ? {} : {};", l.inst_stride, l.open_stride));
        line(out, level + 1, &format!("const vo = s0 ? {} : {};", l.inst_value_offset, l.open_value_offset));
        line(out, level + 1, &format!("vExtent(dv, o0, n0, st, path, '{field}');"));
        line(out, level + 1, "for (let i0 = 0; i0 < n0; i0++) {");
        line(out, level + 2, "const e = o0 + i0 * st;");
        validate_value(out, level + 2, &body.key, "e", field, Some("i0"), set, 1);
        line(out, level + 2, &format!(
            "if (s0) {{ const [lo, hi] = vInstance(dv, e + vo, path, '{field}', i0); __validate{name}Inst(dv, lo, hi, [...path, '{field}', i0]); }}"
        ));
        line(out, level + 2, &format!("else __validate{name}Base(dv, e + vo, 0, [...path, '{field}', i0]);"));
        line(out, level + 1, "}");
        line(out, level, "}");
        return;
    }
    line(out, level, "{");
    line(out, level + 1, &format!("const [o0, n0] = vRegion(dv, {pos}, {stride}, path, '{field}');"));
    line(out, level + 1, "for (let i0 = 0; i0 < n0; i0++) {");
    line(out, level + 2, &format!("const e = o0 + i0 * {stride};"));
    validate_value(out, level + 2, &body.key, "e", field, Some("i0"), set, 1);
    validate_value(out, level + 2, &body.value, &format!("e + {v_off}"), field, Some("i0"), set, 1);
    line(out, level + 1, "}");
    line(out, level, "}");
}
